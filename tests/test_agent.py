def test_промпт_перечисляет_настоящие_разделы():
    """Список возможностей в промпте должен совпадать с разделами отчёта.

    Иначе ассистент обещает то, чего нет: переименовали раздел — и на вопрос
    «что ты умеешь» он называет несуществующий. Обещание, которого продукт
    не выполняет, хуже отсутствующего.
    """
    from core.report import SECTION_TITLES

    пропущены = [
        название
        for название in SECTION_TITLES.values()
        # в промпте они перечислены в именительном падеже и без заглавной
        if название.split()[0].lower()[:6] not in SYSTEM_PROMPT.lower()
    ]
    assert not пропущены, f"в промпте не названы разделы: {пропущены}"


def test_промпт_разбит_на_блоки():
    """Промпт длинный, и правила в нём разной природы: кто ты, что нельзя решать
    за человека, как обращаться с оценками, как с инструментами. Разметка блоками
    держит их врозь — иначе при следующей правке одно правило дописывается
    в чужой раздел и теряется.

    Блоки перечислены поимённо: пропажа любого означает, что кусок правил
    выпал целиком.
    """
    блоки = re.findall(r"<([A-Z_]+)>", SYSTEM_PROMPT)

    assert блоки == [
        "ROLE",
        "CAN",
        "CANNOT",
        "CORE_RULE",
        "DECISION",
        "MISSING_DATA",
        "RISK_RATINGS",
        "TOOLS",
        "EXTERNAL_SOURCES",
        "STYLE",
    ]
    # Каждый открытый тег закрыт: незакрытый съедает всё до конца промпта
    for блок in блоки:
        assert f"</{блок}>" in SYSTEM_PROMPT, f"блок {блок} не закрыт"


