def test_числа_подаются_с_разрядами_и_порядком():
    """Считать цифры в потоке токенов модель не умеет — это наша задача.

    Замерено на живом прогоне: из `2589790444.0` она вывела «≈ 2.59 млн ₽»,
    взяв мантиссу верно и промахнувшись в порядке в тысячу раз. Ровно то число,
    на котором стоит опорный пример проекта.
    """
    assert amount(2589790444.0) == "2 589 790 444 ₽ (2,59 млрд)"
    assert amount(21685219.0) == "21 685 219 ₽ (21,7 млн)"
    assert amount(0) == "0 ₽"
    # Порядок подсказываем только там, где цифры трудно сосчитать глазом
    assert amount(5832) == "5 832 ₽"
    # Счётчики не деньги: без валюты, но с разрядами
    assert amount(1234, "") == "1 234"


