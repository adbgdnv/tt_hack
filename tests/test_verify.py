"""Сверка чисел ответа с отчётом.

«Не выдумывает» — критерий приёмки кейса, и до этой проверки он держался
на формулировках промпта и ни разу не был измерен.
"""

from __future__ import annotations

from core import verify
from core.report import build

ЗАПИСЬ = {
    "baseInfo": {
        "inn": "5032257375",
        "shortName": 'ООО "МАКСМАРКЕТ"',
        "riskLevel": "LOW",
        "registrationInfo": {"yearsFromRegistration": 9},
    },
    "status": {"status": "CURRENT"},
    "zskRiskLevel": "GREEN",
    "reputationalRisks": {"negative": [], "positive": []},
    "arbitrationByStatus": {"commonCount": 17, "commonAmount": 2589790444},
    "executionProceedings": [{"active": True, "amount": 1000, "date": "2024-05-01"}] * 54,
}

ОТЧЁТ = build(ЗАПИСЬ)


def test_число_из_отчёта_подтверждается():
    итог = verify.check("В отчёте 17 арбитражных дел.", ОТЧЁТ)

    assert [c.number for c in итог.claims] == ["17"]
    assert итог.unverified == 0
    assert итог.share == 1.0


def test_выдуманное_число_помечается_а_не_удаляется():
    """Пользователю нужны и утверждение, и сомнение в нём: удалить утверждение
    значит спрятать сомнение."""
    итог = verify.check("Исков на 999 999 999 ₽.", ОТЧЁТ)

    assert итог.unverified == 1
    (утверждение,) = итог.claims
    assert утверждение.found is False
    assert "999 999 999" in утверждение.context


def test_порядок_словами_считается_тем_же_числом():
    """Отчёт округляет: «2,6 млрд» против 2 589 790 444 — расхождение 0,4%.
    Без учёта порядка модель обвинялась бы в выдумывании того, что прочитала."""
    итог = verify.check("Исков на 2,6 млрд ₽.", ОТЧЁТ)

    assert итог.unverified == 0


def test_соседнее_число_не_считается_подтверждённым():
    """Допуск нужен для округления, а не для того, чтобы подтверждать всё
    подряд: 54 производства и 53 производства — разные утверждения."""
    итог = verify.check("Производств 53.", ОТЧЁТ)

    assert итог.unverified == 1


def test_нумерация_списка_не_утверждение():
    """Иначе каждое перечисление давало бы неподтверждённые утверждения."""
    итог = verify.check("Смотрите:\n1. Первое\n2. Второе\n3. Третье", ОТЧЁТ)

    assert итог.claims == ()


def test_ответ_без_чисел_не_подтверждён_а_не_проверен():
    """Пустой список утверждений значит «проверять было нечего». Выдавать его
    за подтверждение нельзя: такой ответ проверка не покрывает вовсе."""
    итог = verify.check("Данных о лицензиях в отчёте нет.", ОТЧЁТ)

    assert итог.claims == ()
    assert итог.share is None
    assert итог.unverified == 0


def test_проверка_не_ходит_в_сеть():
    """Первая ступень лестницы обязана стоить ноль вызовов модели — иначе
    проверка каждого ответа удваивала бы его цену."""
    итог = verify.check("17 дел и 9 лет.", ОТЧЁТ)

    assert итог.checked is False
