"""Общая подготовка прогона.

Единственная задача — чтобы тесты не зависели от того, что лежит в `.env`
у конкретного разработчика.
"""

from __future__ import annotations

import os

import pytest


@pytest.fixture(autouse=True, scope="session")
def _трассировка_выключена() -> None:
    """Выключить трассировку на весь прогон, что бы ни лежало в `.env`.

    `load_env()` кладёт значения через `setdefault`, то есть уже заданная переменная
    сильнее файла. Пользуемся этим: задаём заранее — и строка `LANGSMITH_TRACING=true`
    из личного `.env` до прогона не доходит.

    Без этого набор вёл себя по-разному у разных людей: у того, кто завёл ключ,
    каждый прогон слал записи в LangSmith и тратил квоту, а у остальных нет.
    Библиотека к тому же захватывает состояние один раз на процесс, поэтому
    выключать надо до первого обращения — то есть здесь.
    """
    os.environ["LANGSMITH_TRACING"] = "false"
    os.environ.pop("LANGSMITH_API_KEY", None)
