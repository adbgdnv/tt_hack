"""Инструменты агента.

Ни один тест не обращается ни к модели, ни к службе поиска: проверяется то, что
инструмент отдаёт, а не как модель этим распорядится.
"""

import pytest

from api.agent import search, tools

ОПОРНАЯ = "5032257375"

# Числа настоящие — из ООО «МАКСМАРКЕТ», опорной компании кейса. Сама запись
# собрана вручную: подготовленный набор в репозиторий не коммитится (в нём ФИО
# учредителей), и тесты, требующие его, в CI не запустились бы вовсе.
ЗАПИСЬ = {
    "baseInfo": {"inn": ОПОРНАЯ, "shortName": 'ООО "МАКСМАРКЕТ"'},
    "arbitrationCases": [
        {"year": 2023, "plaintiffAmount": 5832755, "defendantAmount": 0},
        {"year": 2024, "plaintiffAmount": 382176765, "defendantAmount": 2589790444},
    ],
    "finReports": [
        {
            "common": {"year": 2023},
            "liabilities": {"capitals": 365129000, "totalLiabilities": 279450703000},
        }
    ],
}

# Компания без единого графика — таких 22 из 200.
ПУСТАЯ = {"baseInfo": {"inn": "0", "shortName": 'ООО "ПУСТО"'}}


@pytest.fixture
def запись():
    return ЗАПИСЬ


def test_результат_несёт_числа_графика(запись):
    """Числа обязательны. С голым подтверждением «показан» модель дописала ответ
    выдуманной таблицей за 2019–2022 годы со ссылкой на несуществующий источник —
    пустота заполняется правдоподобным."""
    текст, добавка = tools.chart_result(запись, ОПОРНАЯ, "arbitration_years")

    assert "2589790444" in текст  # столько предъявлено как ответчику в 2024
    assert "5832755" in текст  # столько предъявила сама в 2023
    assert добавка["chart"] == {"chart": "arbitration_years", "inn": ОПОРНАЯ}


def test_числа_берутся_из_того_же_кода_что_и_дашборд(запись):
    """Второго расчёта быть не должно: иначе чат и экран разойдутся,
    и проверить ответ станет нельзя."""
    from core.charts import build_charts

    построенный = next(c for c in build_charts(запись) if c.key == "balance")
    текст, _ = tools.chart_result(запись, ОПОРНАЯ, "balance")

    for серия in построенный.series:
        for значение in серия.values:
            if значение is not None:
                assert str(значение) in текст


def test_недоступный_вид_даёт_отказ_с_перечислением(запись):
    """У этой компании нет выручки. Отказ должен называть, что есть,
    иначе модель будет предлагать то же самое снова."""
    текст, добавка = tools.chart_result(запись, ОПОРНАЯ, "revenue_assets")

    assert "нет данных" in текст
    assert "balance" in текст  # что-то из доступного названо
    assert добавка == {}  # событие графика не уйдёт, пустой график не нарисуется


def test_выдуманный_вид_не_рисуется(запись):
    _, добавка = tools.chart_result(запись, ОПОРНАЯ, "круговая_диаграмма")
    assert добавка == {}


def test_компания_без_графиков_получает_честный_отказ():
    """Таких 22 из 200. Пустое полотно хуже отказа: оно выглядит как ответ."""
    текст, добавка = tools.chart_result(ПУСТАЯ, "0", "balance")

    assert "ни одного" in текст
    assert добавка == {}


def test_описание_называет_виды_по_русски():
    """Без русских названий модель выбирает по латинскому ключу и промахивается:
    на пробе дважды выбрала «В какой роли судится» вместо «Суммы исков по годам»."""
    описание = tools.show_chart.description

    for название in [
        "В какой роли судится",
        "Чем обеспечены активы",
        "Выручка и активы",
        "Исполнительные производства",
        "Суммы исков по годам",
    ]:
        assert название in описание


def test_без_ключа_поиск_модели_не_предлагается(monkeypatch, запись):
    """Не заглушка, отвечающая «недоступно»: её описание стоило бы токенов
    на каждом вызове модели при лимите 8 000 в минуту."""
    monkeypatch.delenv("TAVILY_API_KEY", raising=False)

    имена = [t.name for t in tools.build(запись, ОПОРНАЯ)]

    assert имена == ["show_chart"]


def test_с_ключом_появляются_поиск_и_чтение(monkeypatch, запись):
    monkeypatch.setenv("TAVILY_API_KEY", "tvly-тестовый")

    имена = [t.name for t in tools.build(запись, ОПОРНАЯ)]

    assert имена == ["show_chart", "web_search", "fetch_page"]


def test_список_инструментов_закрыт(monkeypatch, запись):
    """Каждый инструмент стоит токенов на каждом вызове модели при квоте
    8 000 в минуту. Три — сознательный потолок, а не текущее состояние."""
    monkeypatch.setenv("TAVILY_API_KEY", "tvly-тестовый")
    assert len(tools.build(запись, ОПОРНАЯ)) == 3
    assert search.MAX_RESULTS == 3
    # Потолок на страницу: без него их сервер отдаёт 14 645 токенов на страницу
    assert search.PAGE_CHARS <= 4000
