"""Темы данных.

Тема — способ достать то, чего нет в собранном отчёте, не сваливая модели
запись целиком. Проверяем три свойства: тема помещается в ответ у любой из 200
компаний, отсутствие данных выражается словами, и на экран не уходят пути
внутри JSON.
"""

from __future__ import annotations

import pytest

from core import topics
from core.repo import load

try:
    НАБОР = load().counterparties
except RuntimeError:
    НАБОР = []

нужен_набор = pytest.mark.skipif(not НАБОР, reason="набор не собран")

# Потолок на один ответ инструмента, в символах. Замерено на всех 200 компаниях:
# самая тяжёлая тема — «надёжность», 3 493 токена ≈ 14 000 символов. Потолок
# держит запас и ловит возврат к перечням: до сводки исполнительные производства
# у одной компании давали 51 620 токенов на тему.
ПОТОЛОК = 16_000


def test_тем_восемь_и_все_из_словаря():
    """Список тем не пишется рядом со словарём, а выводится из него: второй
    список разошёлся бы с первым в первый же день."""
    все = topics.topics()

    assert [t.key for t in все] == [
        "финансы",
        "суды",
        "взыскания",
        "надёжность",
        "управление",
        "деятельность",
        "реквизиты",
        "налоги",
    ]
    for тема in все:
        assert тема.fields, f"тема «{тема.key}» пуста"
        for путь in тема.fields:
            assert тема.key in topics.load()["fields"][путь]["tags"]


def test_сводкой_отдаются_ровно_взрывающиеся_темы():
    """Признак не проставлен руками: он вытекает из того, какие списки решено
    отдавать агрегатами. Иначе он разъехался бы с реальностью."""
    сводкой = {t.key for t in topics.topics() if t.summarize}

    assert сводкой == {"суды", "взыскания"}


@нужен_набор
def test_любая_тема_любой_компании_помещается_в_ответ():
    """Главное свойство. До сводки одна компания с 1 744 производствами давала
    52 294 токена на тему — такой ответ не влезал никуда и ронял диалог."""
    самая_тяжёлая = ("", "", 0)
    for запись in НАБОР:
        for тема in topics.topics():
            размер = len(topics.look_up(запись, тема.key))
            if размер > самая_тяжёлая[2]:
                самая_тяжёлая = (запись["baseInfo"]["inn"], тема.key, размер)

    assert самая_тяжёлая[2] <= ПОТОЛОК, f"тема раздулась: {самая_тяжёлая}"


@нужен_набор
def test_тяжёлая_компания_отдаёт_сводку_а_не_перечень():
    """Перечень из 1 744 производств не отвечает ни на один вопрос, который
    об этих производствах задают."""
    тяжёлая = max(НАБОР, key=lambda z: len(z.get("executionProceedings") or []))
    производств = len(тяжёлая["executionProceedings"])
    assert производств > 1000, "в наборе не стало компании с тяжёлым хвостом"

    текст = topics.look_up(тяжёлая, "взыскания")

    assert f"Всего производств: {производств}" in текст
    assert "По годам возбуждения" in текст
    # Номера производств поимённо не перечисляются — иначе смысла в сводке нет
    assert текст.count("\n") < 10


@нужен_набор
def test_нет_данных_говорится_словами():
    """Молчание про лицензии неотличимо от «лицензий нет», а это разные
    утверждения. Отсутствие данных — такой же ответ, как их наличие."""
    без_лицензий = next(з for з in НАБОР if not (з.get("licenses") or []))

    текст = topics.look_up(без_лицензий, "деятельность")

    assert "Лицензии: данных нет." in текст


def test_несуществующая_тема_перечисляет_доступные():
    """Пустоту модель заполняет правдоподобным. Перечень возвращает её в рамки."""
    текст = topics.look_up({}, "криптовалюта")

    assert "Темы «криптовалюта» нет" in текст
    for тема in topics.topics():
        assert тема.key in текст


@нужен_набор
def test_на_экран_не_уходят_пути_внутри_json():
    """Кейсодатель отдельным пунктом просил вычистить интерфейс от технических
    терминов, а взятое по теме видит и пользователь."""
    for запись in НАБОР[:50]:
        for тема in topics.topics():
            текст = topics.look_up(запись, тема.key)
            for кусок in ("finReports[]", "baseInfo.", "arbitrationByStatus", "[]."):
                assert кусок not in текст
