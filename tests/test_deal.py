"""Условия сделки: разбор реплики, слияние и то, что уходит в промпт.

Разбор проверяется на формулировках из `docs/roles_situations.md` — это
ситуации, отобранные и подтверждённые кейсодателем, а не придуманные под тест.
"""

from core import deal as deals
from core.deal import Deal

# ─────────────────────────── разбор реплики ───────────────────────────


def test_ситуация_из_роли_разбирается_целиком():
    """«Менеджер принёс договор на подпись, аванс 40%» — базовая ситуация
    предпринимателя из таблицы ролей."""
    разобрано = deals.from_text(
        "менеджер принёс договор с поставщиком, аванс 3 млн, поставка 45 дней"
    )

    assert разобрано == Deal(side="supplier", scheme="prepay", sum=3_000_000, days=45)


def test_отсрочка_финдиректора_разбирается():
    """«Согласовать отсрочку 60 дней на 3 млн» — ситуация третьей роли."""
    разобрано = deals.from_text("просят согласовать отсрочку 60 дней на 3 млн")

    assert (разобрано.scheme, разобрано.days, разобрано.sum) == ("deferral", 60, 3_000_000)


def test_срок_словом_без_числа():
    assert deals.from_text("дам отсрочку на полгода").days == 180


def test_числа_из_вопроса_об_отчёте_условиями_не_становятся():
    """«Почему иски на 2,6 млрд?» — вопрос про отчёт, а не про сделку. Записать
    его суммой значит придумать пользователю условия, которых он не называл."""
    assert deals.from_text("почему иски на 2,6 млрд?") == Deal()
    assert deals.from_text("покажи выручку за 3 года") == Deal()


def test_названное_позже_переигрывает_прежнее():
    было = Deal(side="supplier", scheme="prepay", sum=3_000_000)

    стало = deals.from_text("а если отсрочка 60 дней?", было)

    assert стало.scheme == "deferral"
    assert стало.days == 60
    # Несказанное не стирается: вопрос был про схему, а не про сумму
    assert стало.sum == 3_000_000
    assert стало.side == "supplier"


def test_реплика_без_условий_ничего_не_меняет():
    было = Deal(scheme="prepay", sum=1_000_000)

    assert deals.from_text("а суды у них какие?", было) == было


# ─────────────────────────── что уходит в промпт ───────────────────────────


def test_пустая_сделка_даёт_указание_спросить():
    """Пункт задачи: если пользователь ситуацию не описал, её надо выяснить —
    но одним вопросом и после ответа, а не допросом вместо ответа."""
    блок = deals.render(Deal())

    assert "не сказал" in блок
    assert "допрос" in блок
    assert "ОДНОЙ строкой" in блок


def test_известные_условия_уходят_словами_и_помечены_как_слова_пользователя():
    блок = deals.render(Deal(side="supplier", scheme="prepay", sum=3_000_000, days=45))

    assert "поставщик" in блок
    assert "аванс" in блок
    assert "3 000 000 ₽" in блок  # формат один с отчётом — иначе это две суммы
    assert "45 дней" in блок
    # Условия — не данные отчёта: выдать их за проверенные сведения нельзя
    assert "со слов пользователя" in блок


def test_неназванное_перечисляется_чтобы_агент_знал_что_спросить():
    блок = deals.render(Deal(scheme="deferral"))

    assert "Не названо" in блок
    assert "сумма сделки" in блок
    assert "аванс, отсрочка" not in блок.split("Не названо")[0]  # схему уже знаем


# ─────────────────────────── порядок противоречий ───────────────────────────


def test_схема_и_роль_задают_теги():
    """Теги берутся из `triggers.INTENTS`, чтобы не разойтись со вторым набором."""
    при_отсрочке = deals.tags(Deal(scheme="deferral"))
    при_авансе = deals.tags(Deal(scheme="prepay"))

    assert "финансы" in при_отсрочке and "взыскания" in при_отсрочке
    assert "надёжность" in при_авансе
    assert deals.tags(Deal()) == ()
