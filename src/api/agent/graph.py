"""Сборка агента и его состояние.

Состояние диалога — это история сообщений и **запись о компании целиком**. Запись
живёт здесь, в контексте выполнения, и в промпт не попадает никогда. Раньше причина
была в лимите: 31 000 токенов на типовой компании при квоте провайдера 8 000 в минуту.
Лимит снят — причина осталась другая и более важная: модель должна видеть ровно то,
что видит пользователь, иначе ответ станет нечем сверить с экраном. В промпт идёт
собранный отчёт, около 2 400 токенов вместе с противоречиями.

Инструменты — это окно модели в запись, а не способ вывалить её в контекст.
Взятое инструментом показывается пользователю блоком вызова — тем же самым
способом, каким показываются находки внешнего поиска.

Берём `langchain.agents.create_agent`, а не `langgraph.prebuilt.create_react_agent`:
второй объявлен устаревшим в LangGraph 1.0 и будет удалён в 2.0.
"""

from __future__ import annotations

from dataclasses import dataclass

from langchain.agents import create_agent
from langchain_core.tools import BaseTool

from core.llm import LLMClient
from core.report import Report

# Сколько раз агент может сходить к модели в рамках одного вопроса. Прежние три
# стояли из-за минутной квоты Groq: один вопрос был способен её выесть. Квоты нет,
# а шагов стало больше — вопрос «стоит ли давать отсрочку» законно тратит запрос
# данных по теме, показ графика и ответ. Предел всё равно нужен: без него цикл
# может не сойтись вовсе.
MAX_STEPS = 6

# Резерв на ответ. Было 700 — по той же минутной квоте. Проверено на живом вызове:
# при 500 токенах `deepseek v4 flash` вернул пустую строку, потому что рассуждение
# съело весь бюджет выхода. Запас обязателен при любой модели с рассуждением.
MAX_TOKENS = 1500


@dataclass
class Context:
    """Всё, что агенту нужно знать сверх переписки.

    `record` — сырая запись из набора. Её читают инструменты; в модель она
    не уходит. `report` — то же самое в виде, который видит пользователь.
    """

    record: dict
    report: Report


def build(tools: list[BaseTool], system_prompt: str, provider: str = "", model: str = ""):
    """Собирает агента. Список инструментов задаёт вызывающий.

    Инструменты приходят снаружи, а не собираются здесь: их набор зависит от
    настроек окружения — без ключа поиска инструмент поиска не создаётся вовсе,
    и модели он не описывается. Описание неработающего инструмента стоило бы
    токенов на каждом вызове.

    `provider` и `model` пусты у обычного вызова — берётся первый настроенный
    путь. Заданы они только при переходе на запасной: отказ основного не должен
    доходить до пользователя ошибкой.
    """
    client = LLMClient(provider=provider, model=model)
    return create_agent(
        # Глубина рассуждения не задаётся здесь: её знает провайдер. У gpt-oss
        # на Groq рассуждение тратится из бюджета ответа и требует ограничения,
        # у моделей OpenRouter такого параметра нет вовсе.
        client.chat(max_tokens=MAX_TOKENS),
        tools,
        system_prompt=system_prompt,
        context_schema=Context,
    )
