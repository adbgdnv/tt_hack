"""Сборка агента и его состояние.

Состояние диалога — это история сообщений и **запись о компании целиком**. Запись
живёт здесь, в контексте выполнения, и в промпт не попадает никогда: замерено
31 000 токенов на типовой компании и до 100 000 на самой тяжёлой из 200, при лимите
провайдера 8 000 токенов в минуту. В промпт идёт собранный отчёт — ровно то, что
видит пользователь на экране, около 1 500 токенов.

Инструменты — это окно модели в запись, а не способ вывалить её в контекст.

Берём `langchain.agents.create_agent`, а не `langgraph.prebuilt.create_react_agent`:
второй объявлен устаревшим в LangGraph 1.0 и будет удалён в 2.0.
"""

from __future__ import annotations

from dataclasses import dataclass

from langchain.agents import create_agent
from langchain_core.tools import BaseTool

from core.llm import LLMClient
from core.report import Report

# Сколько раз агент может сходить к модели в рамках одного вопроса. Двух хватает
# на «вызвал инструмент и ответил», третий оставлен на случай двух инструментов
# подряд — такое наблюдалось: модель вызвала показ графика дважды, исправляя
# собственный промах. Без предела один вопрос способен выесть минутную квоту.
MAX_STEPS = 3

# Резерв на ответ.
MAX_TOKENS = 700

# Глубина рассуждения. Без ограничения агент проваливался ровно на шаге после
# вызова инструмента: модель истратила все 700 токенов на рассуждение о графике
# и вернула пустой ответ с признаком «упёрся в лимит». Замерено на живом
# провайдере: рассуждение 431 токен из 700 по умолчанию против 4 при `low`.
# Пустой ответ после показанного вызова инструмента выглядит как поломка.
REASONING = "low"


@dataclass
class Context:
    """Всё, что агенту нужно знать сверх переписки.

    `record` — сырая запись из набора. Её читают инструменты; в модель она
    не уходит. `report` — то же самое в виде, который видит пользователь.
    """

    record: dict
    report: Report


def build(tools: list[BaseTool], system_prompt: str):
    """Собирает агента. Список инструментов задаёт вызывающий.

    Инструменты приходят снаружи, а не собираются здесь: их набор зависит от
    настроек окружения — без ключа поиска инструмент поиска не создаётся вовсе,
    и модели он не описывается. Описание неработающего инструмента стоило бы
    токенов на каждом вызове.
    """
    client = LLMClient()
    return create_agent(
        client.chat(max_tokens=MAX_TOKENS, reasoning_effort=REASONING),
        tools,
        system_prompt=system_prompt,
        context_schema=Context,
    )
