"""Системный промпт агента и подготовка контекста.

Каждое правило — не вкусовщина, а требование кейсодателя из описания кейса или Q&A.

Известная проблема, из-за которой проверка формулировок входит в приёмку: на пробном
прогоне модель выдала категоричное «Не стоит работать с компанией», хотя правило
про рекомендательный тон в промпте уже было. Одного промпта мало.

Модель получает **тот же отчёт, что видит пользователь** — не больше и не меньше.
Покажи ей больше, и ответ разойдётся с экраном: пользователь не сможет проверить
утверждение, а проверяемость это заявленная ценность продукта.
"""

from __future__ import annotations

from core.report import Report, State
from core.triggers import order_for

SYSTEM_PROMPT = """<ROLE>
Ты помогаешь предпринимателю разобраться в отчёте о контрагенте. Пользователь
видит этот отчёт на экране рядом с тобой. Ты помощник по нему, а не универсальный
ассистент.
</ROLE>

<CAN>
Сказать, что настораживает и почему.
Объяснить любое число и любой раздел: реестры, суды, исполнительные производства,
финансы, регистрация, виды деятельности, руководство, связанные организации.
Объяснить обе оценки риска.
Сказать, чего в отчёте нет.
</CAN>

<CANNOT>
Сравнивать с отраслевыми нормами или другими компаниями.
Писать тексты, переводить, консультировать по праву, говорить на посторонние темы.

Отказ — одна фраза по-русски и предложение спросить по отчёту. Просьба перевести —
тоже посторонняя тема, и отвечать на неё надо по-русски, а не на языке просьбы.

О себе отвечай своими словами: первым предложением кто ты и про какую компанию,
дальше коротко о возможностях. Списки выше — границы, а не заготовка ответа.
</CANNOT>

<CORE_RULE>
Отвечай только по переданному отчёту. Каждое утверждение должно опираться
на конкретный раздел или число из него. Ничего не додумывай и не добавляй
сведений из общих знаний о компаниях.
</CORE_RULE>

<DECISION>
Ты обращаешь внимание на факты и рекомендуешь, но решение принимает человек.
Запрет работает в обе стороны.

Не пиши «не работайте с этой компанией», «отказаться от сделки», «не стоит
сотрудничать».

И ровно так же не пиши «сотрудничество безопасно», «рисков нет», «дополнительный
анализ не требуется», «можно работать» — это то же решение за человека, только
наоборот, и оно опаснее: оно гасит проверку.

Показывай, что именно настораживает и почему.
</DECISION>

<MISSING_DATA>
Данных для ответа в отчёте нет — скажи прямо: «в отчёте этих данных нет»,
и назови, чего именно не хватает. Не заменяй догадкой.

Раздел со состоянием «данных нет» означает, что оценить по этому критерию
невозможно. Это НЕ значит, что рисков нет. Так и формулируй.

Раздел со состоянием «не применимо» означает устройство формы: у ИП не бывает
бухгалтерской отчётности, учредителей и уставного капитала. Так и говори,
а не «данных нет».
</MISSING_DATA>

<RISK_RATINGS>
Оценка риска банка и уровень ЗСК — источник истины. Не спорь с ними
и не пересчитывай. Значение «оценить невозможно» — это не низкий риск.

Почему оценка именно такая, ты не знаешь: методика не раскрывается. Не пиши
«низкий риск, потому что нет просрочек / стабильные показатели / нет дефолтов» —
этого в отчёте нет, это домысел. Можно сказать только, что оценка означает
и кто её выставил.

Низкая оценка и зелёный уровень НЕ отменяют сигналы разделов. Отвечая про любую
из оценок, посмотри на разделы: если там есть на что обратить внимание, скажи
об этом в том же ответе. Светофор считается по своим данным, часть которых
в отчёт не входит, и совпадать с содержимым разделов не обязан. Ответ «оценка
низкая», умалчивающий о банкротстве и исках, вводит в заблуждение сильнее,
чем отсутствие ответа.
</RISK_RATINGS>

<TOOLS>
График показывай, когда о нём просят или когда он объясняет твой ответ лучше слов.
Числа для рассказа бери из результата инструмента, а не из головы.

Искать снаружи можно только когда отчёта не хватает. Отчёт отвечает — не ищи.

Не хватает выдержки из поиска — прочитай страницу по её ссылке. Только по той,
которую поиск уже вернул, и только когда без неё ответить нельзя: чтение стоит
дорого и отнимает время пользователя.

Выдача поиска — не ответ. Бери из неё только то, что отвечает на вопрос.
Не нашлось подходящего — скажи прямо «в открытых источниках по этому вопросу
ничего не нашлось» и не пересказывай, что пришло вместо него.
</TOOLS>

<EXTERNAL_SOURCES>
Найденное снаружи — НЕ факт из отчёта. Выводи его отдельным слоем: сначала
«По отчёту: …», потом «Во внешних источниках: … (ссылка)» с оговоркой, что
отчётом это не подтверждено.

Если найденное совпадает с тем, что уже есть в отчёте, — это подтверждение
отчёта, а не внешнее сведение. Так и говори: «внешние источники подтверждают».
Выдавать данные отчёта за неподтверждённую находку нельзя — это переворачивает
доверие к ним с ног на голову.

Если внешние сведения расходятся с отчётом — верь отчёту и скажи о расхождении
вслух. Отчёт банка первичен, внешние источники его дополняют, а не исправляют.
</EXTERNAL_SOURCES>

<STYLE>
Отвечай коротко и по делу, без вводных фраз и без пересказа всего отчёта.
Главное — вперёд, подробности — по запросу.

Отвечай на русском языке.
</STYLE>"""


# Статус приходит кодом схемы. В наборе он один — CURRENT у всех двухсот, —
# но уходить в модель латиницей он не должен: она перескажет код пользователю,
# а показывать коды схемы запрещено требованиями.
_STATUS_WORDS = {
    "CURRENT": "действующая",
    "LIQUIDATING": "в процессе ликвидации",
    "LIQUIDATED": "ликвидирована",
    "BANKRUPT": "в процедуре банкротства",
    "REORGANIZING": "в процессе реорганизации",
}

# Что сказать модели про каждый светофор. Направление шкалы объявляем явно,
# а не значением: замерено на живом прогоне — из строки «Скоринг банка: Низкий»
# модель вывела «низкий скоринг подтверждает высокий риск», перевернув смысл.
# Шкалой, а не картой «значение → расшифровка», чтобы не дублировать здесь
# словари `report._BANK_RISK` и `_ZSK_RISK` и не разойтись с ними.
_BANK_SCALE = (
    "внутренняя модель банка; шкала Низкий → Средний → Высокий, "
    "«Низкий» значит меньше риска; методика не раскрывается"
)
_ZSK_SCALE = (
    "платформа «Знай своего клиента» Банка России; оценивает риск вовлечённости "
    "в подозрительные операции, а не финансовую устойчивость; это оценка ЦБ, "
    "а не банка; шкала Зелёный → Жёлтый → Красный, «Зелёный» значит меньше риска"
)


def amount(value: float, unit: str = "₽") -> str:
    """Число для модели: разряды пробелами и порядок словами.

    Обязательно и то, и другое. Замерено на живом прогоне: из `2589790444.0`
    модель вывела «≈ 2.59 млн ₽» — мантиссу взяла верно, порядок промахнула
    в тысячу раз. Считать цифры в потоке токенов языковые модели не умеют,
    и это наша задача, а не их.

    Интерфейс форматирует суммы сам, компонентом дизайн-системы (см. `Fact`).
    Здесь отдельная реализация не потому, что о ней забыли: у модели другой
    потребитель и другие требования — ей нужен порядок словами, человеку на
    экране он не нужен.
    """
    целое = int(round(value))
    разряды = f"{целое:,}".replace(",", " ")
    хвост = f" {unit}" if unit else ""
    порядок = ""
    if abs(целое) >= 1_000_000_000:
        порядок = f" ({целое / 1_000_000_000:.2f} млрд)".replace(".", ",")
    elif abs(целое) >= 1_000_000:
        порядок = f" ({целое / 1_000_000:.1f} млн)".replace(".", ",")
    return f"{разряды}{хвост}{порядок}"


def _fact_value(fact) -> str:
    """Значение факта для модели: деньги и счётчики с разрядами, статус словами.

    Статус лежит в разделе ещё и фактом, не только в шапке. Переводим здесь,
    а не в `report.py`: интерфейс переводит его сам (`ReportSection.tsx`),
    и сырой код нужен ему как ключ. У модели ключей нет — ей нужен русский,
    иначе она перескажет пользователю `CURRENT`.
    """
    if fact.kind in {"money", "count"} and isinstance(fact.value, int | float):
        return amount(fact.value, "₽" if fact.kind == "money" else "")
    return _STATUS_WORDS.get(str(fact.value), str(fact.value))


_STATE_WORDS = {
    State.SIGNAL: "есть на что обратить внимание",
    State.FILLED: "данные есть, ничего не сработало",
    State.EMPTY: "данных нет, оценить невозможно",
    State.NOT_APPLICABLE: "не применимо к этой форме собственности",
}


def render_report(report: Report, triggers: tuple | None = None) -> str:
    """Отчёт в текст для модели — ровно то, что видит пользователь на экране.

    Формат плотный: у провайдера лимит считает вход, а отчёт со всеми разделами
    должен оставаться дешёвым, чтобы диалог не упирался в минутную квоту.
    """
    форма = "индивидуальный предприниматель" if report.is_entrepreneur else "юридическое лицо"
    lines = [
        f"Контрагент: {report.name}, ИНН {report.inn}",
        f"Форма: {форма}",
        f"Статус: {_STATUS_WORDS.get(report.status, report.status)}",
    ]
    if report.years is not None:
        lines.append(f"Лет с регистрации: {report.years}")
    lines.append(
        f"{report.bank_risk.source} ({_BANK_SCALE}): {report.bank_risk.value}"
        + ("" if report.bank_risk.known else " — оценки нет, и это не низкий риск")
    )
    lines.append(
        f"{report.zsk_risk.source} ({_ZSK_SCALE}): {report.zsk_risk.value}"
        + ("" if report.zsk_risk.known else " — оценки нет")
    )
    lines.append("")
    lines.append("РАЗДЕЛЫ ОТЧЁТА:")
    for section in report.sections:
        lines.append(f"— {section.title}: {_STATE_WORDS[section.state]}")
        for factor in section.factors:
            lines.append(f"    • {factor.heading}. {factor.explanation}")
        for fact in section.facts:
            lines.append(f"    {fact.label}: {_fact_value(fact)}")
        # Ряды графиков идут в контекст теми же числами, что нарисованы на экране.
        # Иначе ответ про выручку разойдётся с графиком рядом, и проверить его
        # будет нельзя — а проверяемость и есть смысл продукта.
        for chart in section.charts:
            for ряд in chart.series:
                значения = ", ".join(
                    f"{label} — {amount(value, ряд.unit)}"
                    for label, value in zip(chart.labels, ряд.values, strict=False)
                    if value is not None
                )
                if not значения:
                    continue
                # У столбчатых графиков смысл несут подписи, а не название серии:
                # оно там совпадает с заголовком и повторять его незачем.
                подпись = chart.title if chart.form == "bars" else f"{chart.title} — {ряд.name}"
                lines.append(f"    {подпись}: {значения}")

    # Противоречия между блоками — отдельным списком после разделов.
    #
    # В сами разделы они не встраиваются намеренно: противоречие живёт между
    # двумя разделами, и приписать его одному значит потерять вторую половину.
    # Пустой список тоже проговаривается: у 147 компаний из 200 противоречий
    # нет, и модель должна отвечать «не нашлось», а не молчать.
    lines.append("")
    показать = report.triggers if triggers is None else triggers
    if показать:
        lines.append("ПРОТИВОРЕЧИЯ В ДАННЫХ (найдены нами, не из признаков источника):")
        for триггер in показать:
            lines.append(f"— {триггер.title}. {триггер.explanation}")
            for основание in триггер.evidence:
                lines.append(f"    • {основание}")
    else:
        lines.append("ПРОТИВОРЕЧИЙ В ДАННЫХ не найдено.")
    return "\n".join(lines)


def system_prompt(report: Report, chart_titles: list[str], question: str = "") -> str:
    """Системная часть: правила плюс отчёт плюс доступные графики.

    Единственная сборка контекста на все каналы. Раньше их было две — эта для
    потока и `build_messages` для обычной ручки, — и вторая отстала: коммит 006
    добавил в общий `SYSTEM_PROMPT` правила про инструменты и снял границу
    «искать вне отчёта не умеешь», а инструменты дал только потоку. Обычная ручка
    стала обещать то, чего у неё не было. Теперь инструменты есть у обеих,
    и сборка одна — разойтись им больше нечем.

    Отчёт кладём в системную часть, а не отдельным сообщением: она одна
    и постоянная, а история сообщений растёт. Так отчёт не дублируется по мере
    разговора — при лимите провайдера в 8 000 токенов в минуту это заметно.

    Список доступных графиков обязателен: у 22 компаний из 200 нет ни одного,
    и без списка модель предлагает то, чего построить нельзя.
    """
    отчёт = render_report(report, order_for(report.triggers, question))
    parts = [SYSTEM_PROMPT, f"\nОТЧЁТ О КОНТРАГЕНТЕ:\n{отчёт}"]
    if chart_titles:
        parts.append(
            "\nГрафики, которые можно показать по этой компании: "
            + ", ".join(f"«{t}»" for t in chart_titles)
            + ". Других у неё нет."
        )
    else:
        parts.append("\nПо этой компании нельзя построить ни одного графика — данных нет.")
    return "\n".join(parts)


def conversation(question: str, history: list[dict] | None = None) -> list[dict]:
    """Переписка для агента: ход разговора и вопрос. Системная часть и отчёт
    приходят отдельно — их складывает `system_prompt`."""
    return [*(history or []), {"role": "user", "content": question}]
