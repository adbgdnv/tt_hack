"""Инструменты агента.

Их три, и список закрыт не из скромности: схема каждого инструмента уходит
в модель **на каждом вызове**. Замерено: схема одного инструмента ≈400 токенов,
строка перечня внутри его описания ≈15–29 — в полтора десятка раз дешевле.
Поэтому растут перечни (виды графиков, темы данных), а не список инструментов.

Запись о контрагенте инструменты читают из контекста выполнения, а не получают
параметром: в промпт она не попадает, и модель о ней не знает — она знает только
про инструменты. Причина не в лимите провайдера (он снят), а в проверяемости:
модель должна видеть ровно то, что видит пользователь, и всё взятое сверх отчёта
показывается ему блоком вызова.

Контракты — `specs/006-chat-agent-tools/contracts/tools.md`
и `specs/010-agent-upgrade/contracts/look-up.md`.
"""

from __future__ import annotations

from langchain_core.tools import tool
from langgraph.runtime import get_runtime

from api.agent.graph import Context
from api.agent.prompt import amount
from core import topics as топики
from core.charts import build_charts
from core.topics import catalogue
from core.topics import look_up as look_up_topic

# Русское название рядом с ключом — часть контракта, а не украшение. Без него
# модель выбирает по латинскому ключу и промахивается: на пробе дважды выбрала
# «В какой роли судится» в ответ на просьбу показать суммы исков по годам.
# Виды сгруппированы по разделу отчёта: модель выбирает вид по смыслу вопроса,
# и соседство «выручка / прибыль / активы» помогает ей не промахнуться разделом.
# Названия дословно совпадают с заголовками графиков на экране — иначе ответ
# модели про «Выручку и активы» и подпись под картинкой разойдутся.
#
# Растёт этот перечень, а не список инструментов. Замерено: схема одного
# инструмента стоит ≈400 токенов на каждом вызове модели, строка перечня ≈29 —
# в четырнадцать раз дешевле. Десять графиков отдельными инструментами съели бы
# на одни описания больше, чем стоит весь отчёт о компании.
CHART_KINDS = """
- revenue_assets — «Выручка и активы по годам»
- profit_years — «Прибыль по годам»
- balance — «Чем обеспечены активы»
- asset_mix — «Из чего состоят оборотные активы»
- liability_mix — «Из чего состоят краткосрочные обязательства»
- plaintiff_defendant — «В какой роли судится»
- case_outcome — «Чем закончились дела»
- arbitration_years — «Суммы исков по годам»
- proceedings — «Исполнительные производства»
- proceedings_years — «Когда возбуждались производства»
"""


def _values(spec) -> str:
    """Числа графика строкой — для модели.

    Обязательны. С голым подтверждением «график показан» модель дописывает ответ
    выдуманной таблицей: на пробе нарисовала 2019–2022 годы, которых в отчёте нет,
    и приписала «данные основаны на публичных реестрах». Пустота заполняется
    правдоподобным, поэтому пустоты быть не должно.
    """
    return "; ".join(
        f"{series.name}: "
        + ", ".join(
            # Разряды и порядок словами — тем же кодом, что и в отчёте. Голое
            # `2589790444.0` модель прочитала как «2.59 млн», промахнувшись
            # в тысячу раз: считать цифры в потоке токенов она не умеет.
            f"{label} — {amount(value, series.unit)}"
            for label, value in zip(spec.labels, series.values, strict=False)
            if value is not None
        )
        for series in spec.series
    )


def chart_result(record: dict, inn: str, kind: str) -> tuple[str, dict]:
    """Что вернуть на просьбу показать график. Вынесено из инструмента, чтобы
    проверялось без цикла агента и его контекста выполнения."""
    charts = {c.key: c for c in build_charts(record)}
    spec = charts.get(kind)
    if spec is None:
        available = ", ".join(charts) or "ни одного"
        return (
            f"У этой компании нет данных для графика «{kind}». Доступны: {available}. "
            "Пустой график не показан.",
            {},
        )
    return (
        f"График «{spec.title}» показан пользователю. Его данные: {_values(spec)}",
        {"chart": {"chart": spec.key, "inn": inn}},
    )


@tool(response_format="content_and_artifact")
def show_chart(kind: str) -> tuple[str, dict]:
    """Показать пользователю график по компании из отчёта.

    Виды графиков:
    {kinds}
    Другие виды построить нельзя. Если у компании нет данных для выбранного вида,
    инструмент так и скажет и перечислит доступные.
    """
    runtime = get_runtime(Context)
    return chart_result(runtime.context.record, runtime.context.report.inn, kind)


# Описание достаётся модели как есть, поэтому список видов подставляем в него,
# а не держим отдельной строкой, которую модель не увидит.
show_chart.description = (show_chart.description or "").replace("{kinds}", CHART_KINDS.strip())


@tool(response_format="content_and_artifact")
def look_up(topic: str) -> tuple[str, dict]:
    """Посмотреть данные о компании по теме, которой нет в отчёте.

    Отчёт показывает не всё: в нём нет системы налогообложения, лицензий,
    состава учредителей с долями, госзакупок, филиалов, проверок надзорных
    органов. Зови, когда вопрос про такое.

    Темы:
    {topics}
    Других тем нет. Взятое по теме увидит и пользователь, поэтому ссылайся
    на него в ответе так же свободно, как на отчёт.
    """
    runtime = get_runtime(Context)
    текст = look_up_topic(runtime.context.record, topic)
    if топики.topic(topic) is None:
        # Промах по названию темы — не данные, а подсказка модели: перечень
        # доступных тем. В ленту его показывать нечего, и блок вызова с текстом
        # «такой темы нет» только сбивает читающего.
        return текст, {}
    # Пользователю показываем ровно то, что увидела модель. Иначе она отвечает
    # по данным, которых нет на экране, и проверить ответ становится нечем —
    # а проверяемость и есть заявленная ценность продукта.
    return текст, {"lookup": {"topic": topic, "text": текст}}


look_up.description = (look_up.description or "").replace("{topics}", catalogue())


def build(record: dict, inn: str) -> list:
    """Инструменты для одного запроса.

    Набор зависит от окружения: инструмент, который не может работать, модели
    не предлагается вовсе. Заглушка, отвечающая «поиск недоступен», стоила бы
    токенов на каждом вызове и ничего бы не давала.
    """
    from api.agent import search  # локально: без ключа модуль поиска не нужен

    return [show_chart, look_up, *search.tools()]
