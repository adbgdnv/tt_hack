"""Новости о контрагенте из внешних открытых источников.

Конвейер задан жёстко: поиск → чтение найденных страниц → одна оценка моделью.
Агенту это не поручено намеренно. Агент сам решает, звать ли инструмент, и на
вопрос «что про компанию пишут» мог не позвать поиск ни разу; здесь шаги
выполняются всегда и в одном порядке, а модель отвечает только за суждение
о каждой находке.

Живёт в слое API, а не в ядре: ходит в сеть по MCP, а ядро протоколов не знает
(принцип II конституции). Ядро от этого модуля не зависит — отчёт собирается
и открывается, даже когда внешний источник лежит.

Иерархия источников задана кейсодателем дословно: найденное здесь — всегда
со ссылкой и всегда отдельным слоем, смешивать с фактами отчёта нельзя.
"""

from __future__ import annotations

import asyncio
import time
from dataclasses import dataclass, field

from pydantic import BaseModel, Field

from api.agent import search
from core.llm import LLMClient, chain

# Сколько находок доводим до оценки. Каждая — это чтение страницы и её текст
# в промпте, а лимит провайдера 8 000 токенов в минуту общий с диалогом.
MAX_ITEMS = 3

# Потолок на страницу для новостей — жёстче, чем у инструмента агента (4 000).
# Замерено: три страницы по 4 000 знаков это около 5 400 токенов, две трети
# минутного бюджета за один экран. По 1 500 знаков — около 2 000 на все три.
PAGE_CHARS = 1500

# Сколько держим оценку. Набор статичен, новости меняются не по минутам,
# а повторный заход на ту же компанию не должен стоить ни запроса, ни токенов.
TTL_SECONDS = 6 * 3600

# Запас на ответ. Прежние 700 стояли под gpt-oss с `reasoning_effort="low"`,
# и на deepseek блок сломался: рассуждение съело 612 токенов из 700, ответ
# не распарсился, а пользователь увидел «внешний поиск не отвечает» — сбой
# связи вместо сбоя бюджета. Запас обязателен везде, где ответ разбирается
# по схеме.
ОТВЕТ_ТОКЕНОВ = 2000

# Сколько ждём один путь. Клиент по умолчанию ждёт 90 секунд, а путей три —
# зависший провайдер держал бы блок четыре с половиной минуты. Замерено:
# нормальная оценка занимает 6–7 секунд, так что 25 секунд это уже зависание,
# а не работа. Блок фоновый: пользователь ждёт его меньше, чем ответа в диалоге.
ТАЙМАУТ = 25.0

# Уровни ровно те, что различает модель. «Не про эту компанию» — не оценка,
# а отбраковка: поиск по названию находит справочники, сайты-агрегаторы
# и однофамильцев, и выдавать их за новости о контрагенте нельзя.
ALARMING = "тревожная"
NEUTRAL = "нейтральная"
IRRELEVANT = "не про эту компанию"


class _Judgement(BaseModel):
    """Оценка одной находки. Схема уходит в модель, поэтому поля короткие."""

    index: int = Field(description="Номер находки из списка, начиная с 1")
    level: str = Field(description=f"Одно из: «{ALARMING}», «{NEUTRAL}», «{IRRELEVANT}»")
    # Отдельным полем, а не частью уровня. Проверено на живом ответе: модель
    # исправно писала в summary «выступает как иное лицо» и всё равно ставила
    # «тревожная». Роль она различает, а применить её к оценке не может —
    # так пусть отвечает на прямой вопрос, а вывод делает код.
    party: bool = Field(
        description="Компания — сторона события (её банкротят, к ней иск), "
        "а не сторонний участник вроде «иного лица» или третьего лица"
    )
    summary: str = Field(description="Одна фраза о том, что случилось. Только из текста находки")


class _Assessment(BaseModel):
    judgements: list[_Judgement]


@dataclass(frozen=True)
class Item:
    """Новость с оценкой. Ссылка обязательна: без неё проверить нечего."""

    title: str
    url: str
    summary: str
    level: str


@dataclass(frozen=True)
class News:
    """Новости о компании на момент проверки.

    `failed` отделяет «внешний источник не ответил» от «новостей не нашлось».
    Смешать их значит выдать сбой связи за факт о компании — ровно та ошибка,
    против которой сделан весь остальной продукт.
    """

    items: tuple[Item, ...] = ()
    level: str = ""
    failed: bool = False
    checked_at: float = field(default_factory=time.time)


SYSTEM = """Ты оцениваешь новости о компании для проверки контрагента.

Оценивай КАЖДУЮ находку отдельно и только по приведённому тексту. Ничего
не додумывай: чего в тексте нет, того не было.

Два правила, без которых оценка получается неверной:

1. РОЛЬ. Если текст называет роль компании в событии — сохрани её. Дело
   о банкротстве, где компания «иное лицо» или третье лицо, это не её
   банкротство. Иск, где она истец, это не иск к ней.
2. ДАТЫ. Строки бывают датированы, и поздняя отменяет раннюю. «На 04.09
   решений о приостановке счетов нет» после «на 28.08 решения есть» означает,
   что приостановки нет.

Уровни:
- «{alarming}» — в тексте есть событие, которое случилось С ЭТОЙ компанией
  и влияет на решение работать с ней: её банкротство, взыскание с неё, иск
  к ней, санкции, уголовное дело, отзыв лицензии, приостановка счетов,
  срыв поставок. Событие, где она сторонний участник, сюда не относится.
- «{neutral}» — текст о компании, но такого события в нём нет либо оно
  её напрямую не касается.
- «{irrelevant}» — текст не об этой компании либо это справочник, карточка
  реквизитов, каталог или страница самой компании, а не новость.

`summary` — одна фраза о том, что произошло, словами текста. Если в тексте
есть дата события — начни с неё. Роль компании назови, если текст её называет.
Не пересказывай весь текст и не добавляй оценок от себя. Для «{irrelevant}»
оставь пустую строку.
"""

_cache: dict[str, News] = {}


def enabled() -> bool:
    """Настроен ли внешний поиск. Без ключа блок новостей не показывается вовсе —
    пустой блок читался бы как «новостей нет»."""
    return search.enabled()


def _query(name: str, inn: str) -> str:
    """Запрос поиска.

    Без слов «суд», «банкротство» и подобных намеренно: они превращают поиск
    в подтверждение собственной гипотезы — найдётся ровно то, что спросили,
    и у чистой компании тоже. Спрашиваем про компанию, оценку даёт модель.
    """
    return f"{name} ИНН {inn} новости"


async def _pages(found: list[dict], name: str) -> list[str]:
    """Тексты найденных страниц. Читаются разом: три последовательных запроса
    к чужому серверу — это три задержки сети подряд на открытии экрана."""
    question = f"новости и события о компании {name}"

    async def прочитать(url: str) -> str:
        try:
            return (await search._fetch(url, question))[:PAGE_CHARS]
        except Exception:  # noqa: BLE001 — внешняя система по сети
            # Одна недоступная страница не должна ронять весь блок: остальные
            # находки останутся, а у этой будет только выдержка из поиска.
            return ""

    return list(await asyncio.gather(*(прочитать(f["url"]) for f in found)))


def _assess(found: list[dict], pages: list[str], name: str) -> list[_Judgement]:
    """Оценка находок одним вызовом модели.

    Один вызов на все находки, а не по вызову на каждую: описание задачи
    и правила уходят в модель один раз вместо трёх.
    """
    блоки = []
    for номер, (находка, текст) in enumerate(zip(found, pages, strict=True), start=1):
        # Если страница не прочиталась, судим по выдержке из поиска — она короче,
        # но это всё же текст источника, а не наша догадка.
        содержимое = текст.strip() or находка["snippet"]
        блоки.append(f"Находка {номер}\nЗаголовок: {находка['title']}\nТекст: {содержимое}")

    сообщения = [
        {"role": "system", "content": SYSTEM.format(
            alarming=ALARMING, neutral=NEUTRAL, irrelevant=IRRELEVANT
        )},
        {"role": "user", "content": f"Компания: {name}\n\n" + "\n\n".join(блоки)},
    ]

    # Тот же порядок отхода, что у диалога, — своего у новостей больше нет.
    # Был: бесплатный Groq впереди, чтобы не платить за короткую разметку.
    # Отменено замером на живом сервере — 197 462 из 200 000 токенов Groq
    # в сутки, и блок отвечал «внешний поиск не отвечает», выдавая кончившуюся
    # квоту за сбой связи. Разметка одной новости на основной модели стоит
    # около трёх десятых цента: экономия не стоила пропадающего блока.
    последняя: Exception | None = None
    for путь in chain() or (None,):
        try:
            модель = LLMClient(
                provider=путь.provider if путь else "",
                model=путь.model if путь else "",
                timeout=ТАЙМАУТ,
            ).chat(max_tokens=ОТВЕТ_ТОКЕНОВ)
            ответ = модель.with_structured_output(_Assessment).invoke(
                сообщения,
                config={
                    "run_name": "counterparty-news",
                    "metadata": {
                        "company": name,
                        "provider": путь.provider if путь else "по умолчанию",
                    },
                },
            )
            return list(ответ.judgements)
        except Exception as ошибка:  # noqa: BLE001 — решение о запасном пути здесь
            последняя = ошибка
    raise последняя or RuntimeError("оценщик новостей не настроен")


def _items(found: list[dict], оценки: list[_Judgement]) -> tuple[Item, ...]:
    """Находки с оценками → то, что уходит на экран.

    Вынесено из `collect`, чтобы проверялось без сети: вся суть здесь, а не
    в запросах.
    """
    по_номеру = {суждение.index: суждение for суждение in оценки}
    return tuple(
        Item(
            title=находка["title"],
            url=находка["url"],
            summary=(суждение.summary or "").strip(),
            # Тревожно только то, что случилось с самой компанией. Дело
            # о банкротстве, где она «иное лицо», остаётся на экране со своей
            # формулировкой — но не красит весь блок в тревожный.
            level=суждение.level if суждение.party else NEUTRAL,
        )
        for номер, находка in enumerate(found, start=1)
        if (суждение := по_номеру.get(номер)) and суждение.level != IRRELEVANT
    )


def _level(items: tuple[Item, ...]) -> str:
    """Общий уровень — арифметика, а не суждение модели.

    Модель судит о каждой находке в отдельности, где у неё перед глазами текст.
    Свести три оценки в одну она может только по памяти о них, и это лишний
    повод ошибиться там, где достаточно правила.
    """
    if any(item.level == ALARMING for item in items):
        return ALARMING
    return NEUTRAL if items else ""


async def collect(name: str, inn: str) -> News:
    """Новости о компании: поиск, чтение, оценка. Результат кэшируется по ИНН."""
    свежее = _cache.get(inn)
    if свежее and time.time() - свежее.checked_at < TTL_SECONDS:
        return свежее

    try:
        found = (await search._search(_query(name, inn)))[:MAX_ITEMS]
    except Exception:  # noqa: BLE001 — внешняя система по сети
        return News(failed=True)  # в кэш не кладём: сбой не должен жить шесть часов

    if not found:
        итог = News(items=(), level="")
        _cache[inn] = итог
        return итог

    pages = await _pages(found, name)
    try:
        оценки = await asyncio.to_thread(_assess, found, pages, name)
    except Exception:  # noqa: BLE001 — модель по сети, отказывает и по лимиту тоже
        return News(failed=True)

    items = _items(found, оценки)
    итог = News(items=items, level=_level(items))
    _cache[inn] = итог
    return итог
