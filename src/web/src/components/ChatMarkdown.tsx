import { memo } from 'react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

/**
 * Разбор разметки в ответе ассистента.
 *
 * Модель отвечает в markdown, и до этого компонента мы показывали его как есть:
 * пользователь читал `**Поиск в новостях:**` вместо заголовка. Ответ выглядел
 * как отладочный вывод, а не как ответ.
 *
 * `remark-gfm` нужен ради таблиц: модель отвечает ими регулярно, а без плагина
 * таблица разбирается как абзац со столбиками из палок.
 *
 * **Разметка страницы намеренно не разбирается.** `rehype-raw` не подключён,
 * поэтому теги из ответа модели просто не попадают в дерево. Это сильнее
 * фильтрации: нечего обходить, потому что разбора нет. Ответ приходит от внешней
 * модели и несёт выдержки из внешних источников — фильтровать такое было бы
 * ставкой на полноту своего списка запрещённого.
 */

// Объявлены на уровне модуля намеренно: ссылка должна быть стабильной, иначе
// мемоизация ниже не работает — каждый разбор получал бы новый объект.
const COMPONENTS = {
  a: ({ href, children }: { href?: string; children?: React.ReactNode }) => (
    // Новая вкладка и разрыв связи с открывшей страницей. Ссылки ведут
    // на произвольные внешние сайты из результатов поиска, и отдавать им
    // доступ к странице чата нельзя.
    <a href={href} target="_blank" rel="noopener noreferrer nofollow">
      {children}
    </a>
  ),
  table: ({ children }: { children?: React.ReactNode }) => (
    // Своя обёртка: таблица шире панели чата должна прокручиваться внутри себя,
    // а не уводить вбок всю страницу.
    <div className="md-table-scroll">
      <table>{children}</table>
    </div>
  ),
};

/**
 * Один текстовый блок ответа.
 *
 * Мемоизация здесь не украшение: без неё разметка разбирается заново на каждое
 * пришедшее слово. На ответе в 2000 символов это сотни разборов растущей строки.
 * Мемо по тексту означает, что законченные блоки выше по сообщению не трогаются,
 * пока дописывается последний.
 */
export const ChatMarkdown = memo(function ChatMarkdown({ text }: { text: string }) {
  return (
    <div className="md">
      <ReactMarkdown remarkPlugins={[remarkGfm]} components={COMPONENTS}>
        {text}
      </ReactMarkdown>
    </div>
  );
});
