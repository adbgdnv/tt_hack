"""Темы данных: срез записи о компании по одному вопросу.

Отчёт показывает 66 путей данных из 114. Остальное — система налогообложения,
лицензии, состав учредителей с долями, госзакупки, филиалы, причина закрытия —
на экран не попадает, и агент об этом не знает. Тема — способ достать нужное
по запросу, не сваливая запись целиком.

Почему перечень, а не поиск по смыслу. Тем восемь. Выбор среди восьми
подписанных вариантов — это перечисление, а не поиск; векторное хранилище
оправдано, когда вариантов тысячи. Замеры — `specs/010-agent-upgrade/research.md`.

Почему темы выводятся из словаря полей, а не пишутся отдельным списком. Теги
уже проставлены у всех 114 полей в `fields.json`; второй список разошёлся бы
с первым в первый же день. Здесь задаются только названия тем и порядок.

Почему запись целиком всё равно не кладём, хотя она помещается в контекст
OpenRouter: модель должна видеть ровно то, что видит пользователь. Взятое
по теме показывается ему блоком вызова — иначе ответ станет нечем сверить
с экраном.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from functools import lru_cache

from core.fields import label, load
from core.money import amount

# Названия и порядок тем. Из словаря их не вывести: там тег — одно слово,
# а модели нужна фраза, по которой видно, что внутри. Порядок — от того,
# что спрашивают чаще, к тому, что реже.
ТЕМЫ: tuple[tuple[str, str], ...] = (
    ("финансы", "бухгалтерская отчётность по годам и коэффициенты"),
    ("суды", "арбитражные дела: суммы, роли, статусы, годы"),
    ("взыскания", "исполнительные производства"),
    ("надёжность", "статус компании, проверки надзорных органов, репутационные факторы"),
    ("управление", "руководитель, учредители и доли, связанные компании"),
    ("деятельность", "виды деятельности, лицензии, госзакупки, режим налогообложения"),
    ("реквизиты", "адрес, регистрация, контакты, филиалы, размер"),
    ("налоги", "система налогообложения"),
)

# Как называются списки внутри записи. Словарь описывает поля, а не списки,
# которые их содержат, — поэтому названия групп заданы здесь.
ГРУППЫ = {
    "taxSystem[]": "Режимы налогообложения",
    "phones[]": "Телефоны",
    "branchesInfo.branches[]": "Филиалы",
    "foundersInfo.cofounders[]": "Учредители",
    "relatedCompanies[]": "Связанные компании",
    "finReports[]": "Бухгалтерская отчётность по годам",
    "licenses[]": "Лицензии",
    "procurements[]": "Госзакупки",
    "kindsOfActivityInfo.otherKindsOfActivity[]": "Дополнительные виды деятельности",
    "inspections[]": "Проверки надзорных органов",
    "reputationalRisks.negative[]": "Негативные факторы",
    "reputationalRisks.positive[]": "Позитивные факторы",
    "arbitrationCases[]": "Арбитраж по годам",
    "executionProceedings[]": "Исполнительные производства",
}

# Сколько записей списка показываем поимённо. Замерено: у одной компании 1744
# исполнительных производства — 51 620 токенов на одну тему. Перечень такой
# длины не отвечает ни на один вопрос, который о нём задают.
ПРЕДЕЛ = 12

# Сколько лет показываем в разбивке по годам сводки.
ЛЕТ_В_СВОДКЕ = 8


@dataclass(frozen=True)
class Topic:
    """Тема данных: что в неё входит и как отдавать."""

    key: str
    title: str
    fields: tuple[str, ...]
    # Есть ли внутри список, который отдаётся сводкой вместо перечня.
    summarize: bool


def _num(value: object) -> float | None:
    if isinstance(value, bool) or value is None:
        return None
    try:
        return float(str(value).replace(" ", ""))
    except (TypeError, ValueError):
        return None


def _proceedings(items: list[dict]) -> str:
    """Сводка по исполнительным производствам.

    Ровно те величины, что уже посчитаны для графиков «Исполнительные
    производства» и «Когда возбуждались производства»: модель и пользователь
    должны видеть одни и те же числа, иначе ответ станет нечем сверить.
    """
    активных = sum(1 for p in items if p.get("active") is True)
    суммы = [s for s in (_num(p.get("amount")) for p in items) if s]
    по_годам: dict[str, int] = {}
    for item in items:
        год = str(item.get("date") or "")[:4]
        if год.isdigit():
            по_годам[год] = по_годам.get(год, 0) + 1

    строки = [
        f"Всего производств: {len(items)}; "
        f"действующих {активных}, завершённых {len(items) - активных}."
    ]
    if суммы:
        строки.append(
            f"Сумма указана у {len(суммы)} из {len(items)}: "
            f"всего {amount(sum(суммы))}, наибольшее {amount(max(суммы))}."
        )
    if по_годам:
        годы = sorted(по_годам)[-ЛЕТ_В_СВОДКЕ:]
        хвост = f" (показаны последние {len(годы)} лет из {len(по_годам)})" if (
            len(по_годам) > len(годы)
        ) else ""
        строки.append(
            "По годам возбуждения: "
            + ", ".join(f"{г} — {по_годам[г]}" for г in годы)
            + хвост
            + "."
        )
    return "\n".join(строки)


# Списки, которые отдаются сводкой, а не перечнем. Сейчас он один: замерено,
# что взрывается только он. Правило общее — список, чей размер не ограничен
# природой данных, отдаётся агрегатами.
СВОДКИ: dict[str, Callable[[list[dict]], str]] = {
    "executionProceedings[]": _proceedings,
}


def _prefix(path: str) -> tuple[str, str]:
    """Путь → (список, поле внутри его записи). Для одиночного поля список пуст."""
    if "[]" not in path:
        return "", path
    голова, _, хвост = path.partition("[].")
    return f"{голова}[]", хвост


@lru_cache(maxsize=1)
def topics() -> tuple[Topic, ...]:
    """Темы со списком полей. Поля берутся по тегам словаря."""
    поля = load()["fields"]
    собрано = []
    for ключ, название in ТЕМЫ:
        пути = tuple(п for п, статья in поля.items() if ключ in (статья.get("tags") or ()))
        сводкой = any(_prefix(п)[0] in СВОДКИ for п in пути)
        собрано.append(Topic(key=ключ, title=название, fields=пути, summarize=сводкой))
    return tuple(собрано)


def topic(key: str) -> Topic | None:
    return next((t for t in topics() if t.key == key), None)


def catalogue() -> str:
    """Перечень тем для описания инструмента."""
    return "\n".join(f"- {t.key} — {t.title}" for t in topics())


def _dig(node: object, path: str) -> object:
    """Значение по точечному пути внутри словаря. Нет пути — None."""
    for часть in path.split("."):
        if not isinstance(node, dict):
            return None
        node = node.get(часть)
    return node


def _value(path: str, value: object) -> str | None:
    """Значение словами. None — показывать нечего."""
    if value is None or value == "" or value == []:
        return None
    if isinstance(value, bool):
        return "да" if value else "нет"
    число = _num(value) if isinstance(value, int | float) else None
    # Год — не сумма: «2 023» читается как число с разрядами, а не как год.
    год = path.lower().endswith("year") or path.lower().endswith("date")
    if число is not None and not год and abs(число) >= 10_000:
        return amount(число, "")
    return str(value).strip() or None


def _pairs(источник: dict, пути: list[str], внутри: str = "") -> list[str]:
    """Пары «подпись: значение» по списку путей. Пустые пропускаются."""
    строки = []
    for путь in пути:
        лист = путь[len(внутри) :].lstrip(".") if внутри else путь
        значение = _value(лист, _dig(источник, лист))
        if значение is not None:
            строки.append(f"{label(путь)}: {значение}")
    return строки


def look_up(record: dict, key: str) -> str:
    """Данные компании по одной теме — словами словаря, а не путями внутри JSON.

    Несуществующая тема перечисляет доступные: молчание модель заполняет
    правдоподобным, а перечень возвращает её в рамки.
    """
    выбранная = topic(key)
    if выбранная is None:
        return f"Темы «{key}» нет. Доступные темы:\n{catalogue()}"

    одиночные = [п for п in выбранная.fields if _prefix(п)[0] == ""]
    списки: dict[str, list[str]] = {}
    for путь in выбранная.fields:
        группа = _prefix(путь)[0]
        if группа:
            списки.setdefault(группа, []).append(путь)

    блоки: list[str] = []
    строки = _pairs(record, одиночные)
    if строки:
        блоки.append("\n".join(строки))

    for группа, пути in списки.items():
        имя = ГРУППЫ.get(группа, группа)
        записи = _dig(record, группа[:-2])
        записи = [z for z in записи if isinstance(z, dict)] if isinstance(записи, list) else []
        if not записи:
            # Отсутствие данных — это ответ. Молчание про лицензии неотличимо
            # от «лицензий нет», а это разные утверждения.
            блоки.append(f"{имя}: данных нет.")
            continue
        if группа in СВОДКИ:
            блоки.append(f"{имя}\n{СВОДКИ[группа](записи)}")
            continue
        показать = записи[:ПРЕДЕЛ]
        пункты = []
        for запись in показать:
            пары = _pairs(запись, пути, внутри=группа)
            if пары:
                пункты.append("- " + "; ".join(пары))
        хвост = (
            f"\n…и ещё {len(записи) - len(показать)} — показаны первые {ПРЕДЕЛ}."
            if len(записи) > len(показать)
            else ""
        )
        блоки.append(f"{имя} ({len(записи)}):\n" + "\n".join(пункты) + хвост)

    if not блоки:
        return f"По теме «{key}» данных о компании нет."
    название = выбранная.title
    return f"Данные компании по теме «{key}» ({название}):\n" + "\n\n".join(блоки)
