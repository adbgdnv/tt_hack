"""Сверка чисел из ответа с отчётом.

«Не выдумывает» — критерий приёмки кейса, и до сих пор он держался на одних
формулировках промпта: ни разу не измерен. Критерий Demo Day требует
«возможность проверить пользу по понятным показателям», и доля неподтверждённых
утверждений — ровно такой показатель.

Утверждениями считаем числа, а не предложения. Число проверяется сопоставлением
и стоит ноль вызовов модели; предложение — только моделью. Это осознанный
размен: проверка ловит выдуманную сумму и не ловит выдуманное утверждение
без чисел. Полная проверка требовала бы второго вызова на каждый ответ.

Сверяем не с одним отчётом, а со всем, что пользователю показали: отчёт плюс
данные, взятые инструментом по теме, плюс выдержки из внешних источников. Иначе
проверка обвиняет модель в выдумывании кодов ОКВЭД, которые она честно прочитала
во взятых данных, — замерено, 14 ложных срабатываний на одном ответе.

Живёт в ядре, потому что не знает ни про модель, ни про протокол: на входе
текст и отчёт, на выходе список утверждений с отметкой. Значит проверяется
без сети и переиспользуется из MCP.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import asdict, dataclass

# Число: разряды пробелами или неразрывными, дробная часть через запятую или точку.
ЧИСЛО = re.compile(r"\d[\d   ]*(?:[.,]\d+)?")

# Порядок словами. Модель пишет «2,6 млрд ₽» там, где в отчёте 2 589 790 444.
ПОРЯДКИ = (
    ("трлн", 1e12),
    ("млрд", 1e9),
    ("млн", 1e6),
    ("тыс", 1e3),
)

# Насколько далеко за числом ищем порядок. «2,6 млрд» — три символа, «2,6 тыс. ₽»
# с пробелом и точкой — пять; десяти хватает с запасом, и в них не поместится
# следующее число.
ХВОСТ = 10

# Допуск сравнения. Отчёт округляет: «2,6 млрд» против 2 589 790 444 — расхождение
# 0,4%. Абсолютный порог в половину единицы делает сравнение точным на маленьких
# числах: 54 производства и 53 производства — разные утверждения.
ДОЛЯ = 0.015
ЕДИНИЦА = 0.5

# Сколько символов вокруг числа показываем человеку. Без контекста «12» ни о чём
# не говорит — непонятно, что именно не подтвердилось.
КОНТЕКСТ = 48

# Нумерация списка или заголовка — не утверждение. «1. Первое» и «2) Второе»
# дали бы неподтверждённые утверждения на каждом перечислении.
#
# До цифры пропускаем любую разметку начала строки: решётки заголовка, маркеры
# списка, значки. Замерено на живом ответе — «### 🟠 6. Блокировки счетов»
# давало неподтверждённое утверждение «6», и пользователь видел обвинение
# модели в выдумывании номера пункта, который она сама же и поставила.
МАРКЕР = re.compile(r"(?:^|\n)[^0-9A-Za-zА-Яа-яЁё]*(\d+)[.)]\s")


@dataclass(frozen=True)
class Claim:
    """Число из ответа и то, нашлось ли оно в отчёте."""

    number: str
    context: str
    found: bool


@dataclass(frozen=True)
class Verification:
    """Итог сверки.

    Пустой `claims` означает «проверять было нечего», а не «подтверждено» —
    ответ без единого числа эта проверка не покрывает вовсе.
    """

    claims: tuple[Claim, ...] = ()
    unverified: int = 0
    # Обращались ли к модели за второй ступенью. Она зовётся только когда
    # сверка числами не сошлась.
    checked: bool = False

    @property
    def share(self) -> float | None:
        """Доля подтверждённого. None — проверять было нечего."""
        if not self.claims:
            return None
        return (len(self.claims) - self.unverified) / len(self.claims)


def _value(raw: str, tail: str) -> float | None:
    """Число словами → величина. Порядок из хвоста учитывается."""
    чистое = raw.replace(" ", "").replace(" ", "").replace(" ", "")
    try:
        значение = float(чистое.replace(",", "."))
    except ValueError:
        return None
    низ = tail.lower()
    for слово, множитель in ПОРЯДКИ:
        if низ.lstrip("  ").startswith(слово):
            return значение * множитель
    return значение


def _found_numbers(text: str) -> list[tuple[str, float, int]]:
    """Все числа текста: как записано, сколько это и где начиналось."""
    найдено = []
    for match in ЧИСЛО.finditer(text):
        сырое = match.group().strip()
        значение = _value(сырое, text[match.end() : match.end() + ХВОСТ])
        if значение is not None:
            найдено.append((сырое, значение, match.start()))
    return найдено


def _walk(node: object) -> list[float]:
    """Все числа отчёта: и посчитанные величины, и те, что записаны словами.

    Обходим отчёт целиком, а не перечисляем поля: перечень отстал бы от отчёта
    в первый же раз, когда в него добавят раздел, и проверка начала бы обвинять
    модель в выдумывании того, что она честно прочитала.
    """
    if isinstance(node, bool) or node is None:
        return []
    if isinstance(node, int | float):
        return [float(node)]
    if isinstance(node, str):
        return [значение for _, значение, _ in _found_numbers(node)]
    if isinstance(node, dict):
        return [ч for значение in node.values() for ч in _walk(значение)]
    if isinstance(node, list | tuple):
        return [ч for элемент in node for ч in _walk(элемент)]
    return []


def known_numbers(report, extras: Sequence[str] = ()) -> tuple[float, ...]:
    """Числа, которыми модели разрешено подтверждать свои слова: отчёт и всё
    остальное, что показали пользователю на том же экране."""
    return tuple(_walk(asdict(report))) + tuple(_walk(list(extras)))


def _matches(значение: float, известные: tuple[float, ...]) -> bool:
    for известное in известные:
        предел = max(ЕДИНИЦА, ДОЛЯ * max(abs(значение), abs(известное)))
        if abs(значение - известное) <= предел:
            return True
    return False


def _markers(text: str) -> set[int]:
    """Позиции чисел, которые нумеруют список или заголовок, а не утверждают.

    Позиция берётся у самой цифры, а не вычисляется отступом от начала совпадения:
    отступ работал, пока перед номером стояли только пробелы, и промахнулся,
    как только перед ним встали решётки заголовка.
    """
    return {match.start(1) for match in МАРКЕР.finditer(text)}


def _context(text: str, start: int, length: int) -> str:
    """Фраза вокруг числа — чтобы человек понял, о чём оно."""
    левый = max(0, start - КОНТЕКСТ)
    правый = min(len(text), start + length + КОНТЕКСТ)
    кусок = text[левый:правый].replace("\n", " ").strip()
    return ("…" if левый > 0 else "") + кусок + ("…" if правый < len(text) else "")


def check(text: str, report, extras: Sequence[str] = ()) -> Verification:
    """Сверяет числа ответа с показанным пользователю. Ни одного обращения к модели.

    `extras` — тексты, которые пользователь увидел рядом с ответом: взятое
    по теме, выдержки из внешних источников. Они такое же основание, как отчёт:
    пользователь видит и их.
    """
    маркеры = _markers(text)
    известные = known_numbers(report, extras)
    claims = []
    for сырое, значение, начало in _found_numbers(text):
        if начало in маркеры:
            continue
        claims.append(
            Claim(
                number=сырое,
                context=_context(text, начало, len(сырое)),
                found=_matches(значение, известные),
            )
        )
    return Verification(
        claims=tuple(claims),
        unverified=sum(1 for c in claims if not c.found),
    )
