"""Заголовки и значимость негативных факторов.

Объяснения фактора берутся из данных: поле `name` заполнено у всех 217 негативных
и 3122 позитивных факторов и содержит готовое русское предложение от кейсодателя.
Своими текстами их не заменяем — чужая редактура исказила бы смысл и разошлась бы
с тем, что пользователь видит в их собственном интерфейсе.

Здесь только заголовки: текст фактора медианно 248 символов, максимум 402 —
в карточку он не помещается. Заголовок это навигация, содержание приходит из источника.

Порядок внутри раздела задают две величины, и они разного рода. **Тяжесть**
(`WEIGHTS`) — суждение: банкротство встречается один раз на двести компаний, но
весит больше, чем сорок пять срабатываний «много кодов ОКВЭД». **Частота**
(`FREQUENCY`) — измерение по набору, и она лишь разрешает ничью внутри одного веса.
Тяжесть всегда старше: редкий пустяк не обгонит частую беду.
"""

from __future__ import annotations

# Заголовки составлены по тексту фактора из выгрузки, чтобы не разойтись
# с источником. Пятнадцать кодов — всё, что встречается на двухстах компаниях.
HEADINGS: dict[str, str] = {
    "arbitrationDefendant": "Ответчик в арбитраже",
    "massOkved": "Много кодов ОКВЭД",
    "executionProceedings": "Действующие исполнительные производства",
    "massAddress": "Массовый адрес регистрации",
    "fnsBlocking": "Блокировки счетов налоговой",
    "profit": "Убыток по отчётности",
    "invalidRegistrationData": "Недостоверные регистрационные данные",
    "invalidAddress": "Фиктивный адрес",
    "massAuthpersons": "Массовый директор или учредитель",
    "invalidAuthpersonsData": "Номинальный руководитель",
    "currentAssets": "Оборотные активы равны нулю",
    "liquidationStatus": "Процедура банкротства",
    "dishonestProvider": "Реестр недобросовестных поставщиков",
    "taxArrears": "Должник ФНС",
    "inspectionWithViolation": "Проверки с нарушениями",
}

UNKNOWN_HEADING = "Особое наблюдение"

# 3 — тяжёлое, 2 — заметное, 1 — контекст.
WEIGHTS: dict[str, int] = {
    "liquidationStatus": 3,
    "invalidAddress": 3,
    "invalidAuthpersonsData": 3,
    "dishonestProvider": 3,
    "taxArrears": 3,
    "fnsBlocking": 3,
    "arbitrationDefendant": 2,
    "executionProceedings": 2,
    "invalidRegistrationData": 2,
    "massAddress": 2,
    "massAuthpersons": 2,
    "currentAssets": 2,
    "profit": 2,
    "inspectionWithViolation": 2,
    "massOkved": 1,
}

MIN_WEIGHT = 1

# Насколько фактор редок: у скольких компаний из 200 он сработал.
#
# Замерено по `dataset/counterparties.json`, воспроизводится
# `scripts/audit_factors.py`. Пересобрали набор — пересчитать им, а не глазами.
#
# Зачем это здесь. Тяжесть выше — суждение о том, насколько плохо. Частота —
# измерение того, насколько это сообщает о конкретной компании. Фактор,
# срабатывающий у каждой второй, говорит о базе, а не о ней: до появления этого
# словаря 55 отчётов из 117 открывались строкой «Ответчик в арбитраже», и при
# равной тяжести порядок решал русский алфавит — «Массовый адрес» обгонял «Убыток
# по отчётности» буквой «М». Ничья была у 29 компаний из 117.
#
# Тяжесть при этом не трогается: редкость разрешает ничью внутри одного веса,
# но никогда не поднимает лёгкий фактор над тяжёлым. Кейсодатель запретил
# скоринг — это порядок показа, а не оценка.
FREQUENCY: dict[str, int] = {
    "arbitrationDefendant": 67,
    "massOkved": 45,
    "executionProceedings": 33,
    "massAddress": 24,
    "fnsBlocking": 18,
    "profit": 10,
    "invalidRegistrationData": 6,
    "invalidAddress": 5,
    "massAuthpersons": 2,
    "invalidAuthpersonsData": 2,
    "currentAssets": 1,
    "liquidationStatus": 1,
    "dishonestProvider": 1,
    "taxArrears": 1,
    "inspectionWithViolation": 1,
}

# Неизвестному коду — так, будто он есть у всех: наверх он не всплывёт.
# Та же осторожность, что и с весом, и по той же причине: про частоту нового
# кода мы не знаем ничего, а редкость поднимает фактор в глаза пользователю.
UNKNOWN_FREQUENCY = 200


def heading(code: str) -> str:
    """Короткий заголовок фактора.

    Неизвестный код не показывается пользователю как есть: увидеть `massOkved`
    на экране — ровно то, что запрещено требованиями. Новый код схемы получит
    нейтральный заголовок, а содержание всё равно придёт из поля `name`.
    """
    return HEADINGS.get(code, UNKNOWN_HEADING)


def weight(code: str) -> int:
    """Значимость фактора для сортировки внутри отчёта.

    Неизвестному коду даётся минимум: поднимать наверх то, о чём мы ничего
    не знаем, значит вводить в заблуждение.
    """
    return WEIGHTS.get(code, MIN_WEIGHT)


def frequency(code: str) -> int:
    """У скольких компаний набора этот фактор сработал.

    Второй ключ сортировки после тяжести: при равном весе выше встаёт то, что
    реже, — оно сообщает о компании больше. Меньше значит выше, поэтому
    неизвестный код получает потолок, а не ноль.
    """
    return FREQUENCY.get(code, UNKNOWN_FREQUENCY)
