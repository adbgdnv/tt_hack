"""Заголовки и значимость негативных факторов.

Объяснения фактора берутся из данных: поле `name` заполнено у всех 217 негативных
и 3122 позитивных факторов и содержит готовое русское предложение от кейсодателя.
Своими текстами их не заменяем — чужая редактура исказила бы смысл и разошлась бы
с тем, что пользователь видит в их собственном интерфейсе.

Здесь только заголовки: текст фактора медианно 248 символов, максимум 402 —
в карточку он не помещается. Заголовок это навигация, содержание приходит из источника.

Значимость задаётся тяжестью, а не частотой. Банкротство встречается один раз
на двести компаний, но весит больше, чем сорок пять срабатываний «много кодов ОКВЭД».
"""

from __future__ import annotations

# Заголовки составлены по тексту фактора из выгрузки, чтобы не разойтись
# с источником. Пятнадцать кодов — всё, что встречается на двухстах компаниях.
HEADINGS: dict[str, str] = {
    "arbitrationDefendant": "Ответчик в арбитраже",
    "massOkved": "Много кодов ОКВЭД",
    "executionProceedings": "Действующие исполнительные производства",
    "massAddress": "Массовый адрес регистрации",
    "fnsBlocking": "Блокировки счетов налоговой",
    "profit": "Убыток по отчётности",
    "invalidRegistrationData": "Недостоверные регистрационные данные",
    "invalidAddress": "Фиктивный адрес",
    "massAuthpersons": "Массовый директор или учредитель",
    "invalidAuthpersonsData": "Номинальный руководитель",
    "currentAssets": "Оборотные активы равны нулю",
    "liquidationStatus": "Процедура банкротства",
    "dishonestProvider": "Реестр недобросовестных поставщиков",
    "taxArrears": "Должник ФНС",
    "inspectionWithViolation": "Проверки с нарушениями",
}

UNKNOWN_HEADING = "Особое наблюдение"

# 3 — тяжёлое, 2 — заметное, 1 — контекст.
WEIGHTS: dict[str, int] = {
    "liquidationStatus": 3,
    "invalidAddress": 3,
    "invalidAuthpersonsData": 3,
    "dishonestProvider": 3,
    "taxArrears": 3,
    "fnsBlocking": 3,
    "arbitrationDefendant": 2,
    "executionProceedings": 2,
    "invalidRegistrationData": 2,
    "massAddress": 2,
    "massAuthpersons": 2,
    "currentAssets": 2,
    "profit": 2,
    "inspectionWithViolation": 2,
    "massOkved": 1,
}

MIN_WEIGHT = 1


def heading(code: str) -> str:
    """Короткий заголовок фактора.

    Неизвестный код не показывается пользователю как есть: увидеть `massOkved`
    на экране — ровно то, что запрещено требованиями. Новый код схемы получит
    нейтральный заголовок, а содержание всё равно придёт из поля `name`.
    """
    return HEADINGS.get(code, UNKNOWN_HEADING)


def weight(code: str) -> int:
    """Значимость фактора для сортировки внутри отчёта.

    Неизвестному коду даётся минимум: поднимать наверх то, о чём мы ничего
    не знаем, значит вводить в заблуждение.
    """
    return WEIGHTS.get(code, MIN_WEIGHT)
