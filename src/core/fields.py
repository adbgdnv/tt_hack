"""Словарь полей: путь внутри данных → человеческие слова и теги.

Нужен для двух вещей сразу.

Первая — подписи на экране. Под графиком стояло
`finReports[].assets.currentAssets.{stocks,receivables,bankroll}`, то есть путь
внутри JSON, показанный пользователю. Кейсодатель отдельным пунктом просил
вычистить интерфейс от технических терминов.

Вторая — теги. Каждое поле помечено тем, на какой вопрос отвечает, и по этим
меткам позже можно подбирать в контекст только относящееся к делу, не суя
запись целиком. Сам подбор в эту фичу не входит, но словарь под него готов.

Файл `fields.json` собирается заранее скриптом и лежит в репозитории: он
строится из спецификации кейсодателя, а та живёт вне репозитория и в образ
не попадает.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

СЛОВАРЬ = Path(__file__).with_name("fields.json")


@lru_cache(maxsize=1)
def load() -> dict:
    """Словарь целиком. Читается один раз на процесс — файл в рантайме не меняется."""
    if not СЛОВАРЬ.exists():
        raise RuntimeError(
            f"Нет словаря полей: {СЛОВАРЬ}\n"
            "Собрать: python3 scripts/build_field_dictionary.py"
        )
    return json.loads(СЛОВАРЬ.read_text(encoding="utf-8"))


def entry(path: str) -> dict:
    """Статья по пути. Пустая, если пути нет — вызывающий сам решает, что делать."""
    return load()["fields"].get(path, {})


def label(path: str) -> str:
    """Короткая подпись для экрана.

    Неизвестный путь возвращается как есть: подставить вместо него выдуманное
    название хуже, чем показать путь, — по пути хотя бы видно, что описания нет.
    """
    return entry(path).get("label") or path


def describe(paths: list[str]) -> str:
    """Подпись источника из нескольких полей, словами и через запятую.

    Порядок сохраняется: он задан тем, кто перечислял поля, и обычно совпадает
    с порядком серий на графике.
    """
    видел: list[str] = []
    for путь in paths:
        текст = label(путь)
        if текст not in видел:
            видел.append(текст)
    return ", ".join(видел)


def tags(path: str) -> tuple[str, ...]:
    return tuple(entry(path).get("tags") or ())


def filled(path: str) -> int:
    """У скольких компаний набора поле заполнено.

    Нужно, чтобы не строить правило на поле, заполненном у трёх компаний,
    не заметив этого.
    """
    return int(entry(path).get("filled") or 0)


def conflicts() -> dict[str, str]:
    """Поля, где спецификация расходится с данными.

    Держим отдельно и на виду: молча разрешить расхождение в пользу одной
    из сторон значит лишить следующего читателя способа об этом узнать.
    """
    return {
        путь: статья["conflict"]
        for путь, статья in load()["fields"].items()
        if статья.get("conflict")
    }
