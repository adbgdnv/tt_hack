"""Условия сделки: зачем пользователь открыл этот отчёт.

Отчёт у всех один, а вопрос «работать или нет» — нет. Аванс, отсрочка и оплата
по факту делают важными разные разделы: при авансе решает способность поставить,
при отсрочке — способность рассчитаться. Без условий агент разбирает отчёт
вообще, и собрать из разбора решение по своей сделке пользователь должен сам —
ровно та работа, которую он и хотел переложить.

Условия берутся из двух мест сразу: из формы над полем ввода и из самой реплики
(«а если аванс 3 млн?»). Второе обязательно — иначе разговор и сохранённый
контекст расходятся, и пользователь получает ответ про отсрочку на вопрос
про аванс.

Условия — **со слов пользователя**, а не из отчёта. Проверить их нечем, поэтому
в промпте они помечены как сказанное пользователем: выдать их за данные значило
бы нарушить «отвечай только по отчёту».

Разбирается правилами, а не моделью: лишний вызов на каждую реплику стоил бы
задержки первого слова, а узнаём мы четыре вещи, каждая — набор слов.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass, replace

from core.money import amount
from core.triggers import INTENTS

# Кого проверяем. Роль контрагента, а не пользователя: «поставщик» значит, что
# поставляет он, а платит пользователь.
SIDES = {
    "supplier": "поставщик",
    "buyer": "покупатель",
}

# Схема расчётов. Три, а не больше: они различаются тем, чей риск больше —
# деньги вперёд, товар вперёд или обмен на месте. Всё остальное — их сочетания.
SCHEMES = {
    "prepay": "аванс или предоплата",
    "deferral": "отсрочка платежа",
    "spot": "оплата по факту",
}

# Какие противоречия поднимать наверх при каждой схеме. Ключи — намерения
# из `triggers.INTENTS`: они отобраны по `docs/roles_situations.md` и
# подтверждены кейсодателем, а второй набор тегов разошёлся бы с первым.
_SCHEME_INTENT = {
    "prepay": "prepayment",
    "deferral": "deferral",
    "spot": "delivery",
}

# Роль контрагента задаёт, чем он может подвести. Поставщик — не поставить
# (суды, управление), покупатель — не заплатить (финансы, взыскания).
_SIDE_INTENT = {
    "supplier": "delivery",
    "buyer": "deferral",
}

_SIDE_WORDS = {
    "supplier": ("поставщик", "поставщика", "подрядчик", "продавец", "исполнител"),
    "buyer": ("покупател", "заказчик", "клиент", "дилер"),
}

# Слова схем — те же, по которым `triggers.intent_of` узнаёт намерение вопроса.
# Здесь они нужны отдельно, потому что намерение отвечает «о чём вопрос»,
# а схема — «что человек собирается сделать», и живёт она дольше одной реплики.
_SCHEME_WORDS = {
    "prepay": ("аванс", "предоплат", "деньги вперёд", "вперёд плач", "залог"),
    "deferral": ("отсроч", "рассроч", "постоплат", "товарный кредит", "с отсрочкой"),
    "spot": ("по факту", "постоплаты нет", "без аванса", "по предъявл"),
}

# Слова, при которых число в реплике считается условием сделки. Без них
# «иски на 2,6 млрд» и «выручка за 3 года» — вопросы про отчёт, а не про сделку,
# и записывать их суммой и сроком значит придумать пользователю условия.
_DEAL_MARKERS = (
    "аванс",
    "предоплат",
    "отсроч",
    "рассроч",
    "постоплат",
    "сделк",
    "договор",
    "контракт",
    "закуп",
    "постав",
    "оплат",
    "плач",
    "срок",
    "сумм",
    "кредит",
    "заказ",
)

_MULTIPLIERS = (
    ("млрд", 1_000_000_000),
    ("миллиард", 1_000_000_000),
    ("млн", 1_000_000),
    ("миллион", 1_000_000),
    ("тыс", 1_000),
)

# Сроки к дням. Нормализуем, потому что «два месяца» и «60 дней» — один срок,
# и хранить их по-разному значит показывать пользователю то, что он не писал.
_PERIODS = (
    ("полгода", 180),
    ("год", 365),
    ("месяц", 30),
    ("недел", 7),
    ("дн", 1),
    ("день", 1),
    ("суток", 1),
)


@dataclass(frozen=True)
class Deal:
    """Что пользователь рассказал о своей сделке.

    Пустой набор — законное состояние: пока человек ничего не сказал, выдумывать
    за него условия нельзя, а спрашивать всё сразу — допрос. Ровно поэтому здесь
    нет ни одного значения по умолчанию кроме «не знаю».
    """

    side: str | None = None
    scheme: str | None = None
    sum: float | None = None
    days: int | None = None
    goal: str | None = None

    @property
    def known(self) -> bool:
        return any((self.side, self.scheme, self.sum, self.days, self.goal))

    def describe(self) -> str:
        """Одна строка для интерфейса: «поставщик · аванс · 3 000 000 ₽ · 60 дней»."""
        части = [
            SIDES.get(self.side or ""),
            SCHEMES.get(self.scheme or ""),
            amount(self.sum, "₽") if self.sum else None,
            f"{self.days} дней" if self.days else None,
            self.goal,
        ]
        return " · ".join(ч for ч in части if ч)


def merge(base: Deal, other: Deal) -> Deal:
    """Названное поверх прежнего. Незаполненное поле не стирает прежнее значение:
    реплика «а если 5 млн?» меняет сумму, а не отменяет схему."""
    return replace(
        base,
        **{
            поле: значение
            for поле, значение in asdict(other).items()
            if значение is not None and значение != ""
        },
    )


def _about_deal(text: str) -> bool:
    """Речь ли в реплике о своей сделке. Числа из вопросов об отчёте условиями
    не становятся."""
    return any(слово in text for слово in _DEAL_MARKERS)


def _sum_in(text: str) -> float | None:
    """Сумма из реплики: «3 млн», «1,5 млн ₽», «500 тыс», «3 000 000».

    Голое число берём только с денежным словом рядом. Иначе «отсрочка 60 дней»
    прочиталась бы суммой в шестьдесят рублей.
    """
    if not _about_deal(text):
        return None
    for множитель, вес in _MULTIPLIERS:
        found = re.search(rf"(\d+(?:[.,]\d+)?)\s*{множитель}", text)
        if found:
            return float(found.group(1).replace(",", ".")) * вес
    found = re.search(r"(\d[\d\s]{2,})\s*(?:₽|руб|р\.)", text)
    if found:
        return float(found.group(1).replace(" ", ""))
    return None


def _days_in(text: str) -> int | None:
    """Срок в днях. «Полгода» без числа — тоже срок, поэтому число необязательно."""
    if not _about_deal(text):
        return None
    for слово, вес in _PERIODS:
        found = re.search(rf"(\d+)\s*{слово}", text)
        if found:
            return int(found.group(1)) * вес
        if слово in text and вес >= 30:
            return вес
    return None


def _key_in(text: str, words: dict[str, tuple[str, ...]]) -> str | None:
    for ключ, слова in words.items():
        if any(слово in text for слово in слова):
            return ключ
    return None


def from_text(text: str, base: Deal | None = None) -> Deal:
    """Условия из реплики поверх уже известных.

    Ничего не узнали — возвращаем прежнее. Молчание не значит «пользователь
    передумал»: он просто спросил о другом.
    """
    низкий = (text or "").lower()
    сказанное = Deal(
        side=_key_in(низкий, _SIDE_WORDS),
        scheme=_key_in(низкий, _SCHEME_WORDS),
        sum=_sum_in(низкий),
        days=_days_in(низкий),
    )
    return merge(base or Deal(), сказанное)


def tags(deal: Deal) -> tuple[str, ...]:
    """Теги противоречий, которые эта сделка делает важными.

    Пустой набор у пустой сделки — тогда порядок остаётся по значимости,
    как было до всякого выяснения.
    """
    по_ключу = {намерение.key: намерение for намерение in INTENTS}
    собранные: list[str] = []
    for карта, значение in ((_SCHEME_INTENT, deal.scheme), (_SIDE_INTENT, deal.side)):
        намерение = по_ключу.get(карта.get(значение or "", ""))
        if намерение:
            собранные.extend(намерение.tags)
    return tuple(dict.fromkeys(собранные))


# Чего не хватает — словами пользователя, а не именами полей: этот список
# уходит в промпт как то, что можно спросить.
_ASK = {
    "side": "кого проверяем — поставщика или покупателя",
    "scheme": "схема расчётов — аванс, отсрочка или оплата по факту",
    "sum": "сумма сделки",
    "days": "срок — отсрочки или поставки",
}


def unknown(deal: Deal) -> tuple[str, ...]:
    return tuple(текст for поле, текст in _ASK.items() if getattr(deal, поле) is None)


def render(deal: Deal) -> str:
    """Блок условий для системной части промпта.

    Пустая сделка тоже даёт блок: агенту нужно сказать не только что известно,
    но и как себя вести, пока не известно ничего.
    """
    if not deal.known:
        return (
            "<СДЕЛКА>\n"
            "Пользователь ещё не сказал, что за сделка. Не начинай с допроса\n"
            "и не задавай четыре вопроса списком: сначала ответь тем, что видно\n"
            "по отчёту, а в конце ОДНОЙ строкой спроси главное — что планируется\n"
            "(аванс, отсрочка, оплата по факту), на какую сумму и срок. Когда\n"
            "от условий зависит сам ответ, скажи об этом прямо: «при авансе важно\n"
            "одно, при отсрочке другое».\n"
            "</СДЕЛКА>"
        )
    строки = ["<СДЕЛКА>", "Условия со слов пользователя (не данные отчёта, проверить их нечем):"]
    if deal.side:
        строки.append(f"— контрагент выступает как {SIDES[deal.side]}")
    if deal.scheme:
        строки.append(f"— расчёты: {SCHEMES[deal.scheme]}")
    if deal.sum:
        строки.append(f"— сумма: {amount(deal.sum, '₽')}")
    if deal.days:
        строки.append(f"— срок: {deal.days} дней")
    if deal.goal:
        строки.append(f"— пользователь хочет: {deal.goal}")
    строки.append(
        "Условия держатся весь разговор, пока пользователь их не изменит. "
        "Разбирая отчёт, связывай факты именно с ними: что при этих условиях "
        "становится важным и почему, чего для решения не хватает."
    )
    не_названо = unknown(deal)
    if не_названо:
        строки.append(
            "Не названо: "
            + "; ".join(не_названо)
            + ". Спрашивай только то, без чего ответ будет другим, и не больше "
            "одного вопроса за ответ."
        )
    строки.append("</СДЕЛКА>")
    return "\n".join(строки)
