"""Сравнение нескольких контрагентов в одной сессии.

Кейсодатель на Q&A назвал этот сценарий целевым и одновременно его ограничил:

- «Потребность есть именно чтобы у агента была тулза сравнивать между собой
  контрагентов, находить **оптимального** среди какой-то группы».
- «Скорее **не ранжирование**. Нужно вывод — с кем лучше не общаться.
  Ранжирование в виде какого-то скора **не требуется**».

Отсюда граница, проходящая через весь модуль: **порядок — можно, балл —
нельзя.** Компании расставляются по сумме значимости сработавших триггеров,
но само число наружу не отдаётся: его нет ни в `Verdict`, ни в ручке.
Балл выглядит как измерение там, где никто ничего не измерял, а порядок
выражает сам себя.

Порядок — от чистого к спорному. Выбирают лучшего, и ответ на «кто лучше»
должен стоять первым; вывод при этом называет обоих — и того, кто выглядит
чище, и того, с кем осторожнее. Это одна и та же просьба кейсодателя,
прочитанная с двух концов.

Своих правил у сравнения нет: и триггеры, и состояния разделов уже посчитаны
для отчёта. Заведи оно свою логику — экран сравнения и экран отчёта разошлись
бы в оценке одной и той же компании.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from core import triggers as tr
from core.report import State
from core.report import build as build_report

# Значимость, с которой триггер перестаёт быть уточняющим вопросом и становится
# поводом для осторожности. Пять — вес трёх правил: молчащие светофоры,
# приписка к статусу и управление конкурсным управляющим. Все три говорят
# о самой компании, а не о числах в её отчётности.
ТРЕВОЖНЫЙ_ВЕС = 5

ЧИСТО = "clean"
УТОЧНИТЬ = "clarify"
ВНИМАНИЕ = "attention"

СЛОВАМИ = {
    ЧИСТО: "вопросов нет",
    УТОЧНИТЬ: "есть вопросы",
    ВНИМАНИЕ: "осторожнее",
}


@dataclass(frozen=True)
class Summary:
    """Вывод по пулу: заголовок и подробность.

    Двумя полями, а не одной строкой: заголовок — ответ на вопрос «кто лучше»
    и читается за взгляд, подробность объясняет. Одной строкой в три предложения
    он набирался крупным шрифтом на три строки и переставал быть заголовком.
    """

    headline: str
    detail: str


@dataclass(frozen=True)
class Verdict:
    """Итог по одному контрагенту внутри группы. Без числового скора — намеренно.

    `level` — не оценка: то же трёхсостояние, что у разделов отчёта. Он нужен
    интерфейсу для цвета точки, не складывается и числом не сравнивается.
    Выводить цвет из русской фразы значило бы завести разбор строк.
    """

    inn: str
    name: str
    level: str
    recommendation: str  # то же словами, для тех, кто читает, а не рисует
    reasons: list[str] = field(default_factory=list)  # каждая — до раздела отчёта
    sections: list[str] = field(default_factory=list)  # разделы этих причин
    gaps: list[str] = field(default_factory=list)  # чего в данных нет
    checks_passed: int = 0
    checks_total: int = 0


def _level(сработавшие: tuple[tr.Trigger, ...]) -> str:
    if not сработавшие:
        return ЧИСТО
    return ВНИМАНИЕ if max(t.weight for t in сработавшие) >= ТРЕВОЖНЫЙ_ВЕС else УТОЧНИТЬ


def _gaps(report) -> list[str]:
    """Разделы, которые проверить было нечем.

    Держим отдельно от причин и показываем рядом с выводом. Наверху списка
    это единственное, что отличает «проверили и чисто» от «проверять было
    нечем»: замерено, компания проходит 14 проверок из 14 при двух разделах
    без данных и читается как безупречная.
    """
    return [
        s.title
        for s in report.sections
        if s.state is State.EMPTY
    ]


def verdict(record: dict) -> Verdict:
    """Вердикт по одной компании. Ничего своего не считает."""
    report = build_report(record)
    сработавшие = report.triggers
    уровень = _level(сработавшие)
    return Verdict(
        inn=report.inn,
        name=report.name,
        level=уровень,
        recommendation=СЛОВАМИ[уровень],
        reasons=[t.title for t in сработавшие],
        sections=[t.section for t in сработавшие],
        gaps=_gaps(report),
        checks_passed=sum(s.checks_passed for s in report.sections),
        checks_total=sum(s.checks_total for s in report.sections),
    )


def _weight(record: dict) -> int:
    return sum(t.weight for t in tr.build(record))


def compare(reports: list[dict]) -> list[Verdict]:
    """Разбирает группу контрагентов: от чистого к спорному.

    Порядок задаётся здесь, а не сортировкой на клиенте: «сверху тот, к кому
    меньше вопросов» — утверждение о компаниях, а не украшение таблицы,
    и клиент, отсортировавший иначе, сделал бы вывод неверным.

    При равной значимости выше тот, у кого больше пройденных проверок: между
    двумя одинаково чистыми компаниями честнее поставить выше проверенную,
    а не ту, которую было нечем проверить.
    """
    вердикты = [(verdict(з), _weight(з)) for з in reports]
    вердикты.sort(key=lambda пара: (пара[1], -пара[0].checks_passed))
    return [в for в, _ in вердикты]


def shortlist(reports: list[dict], limit: int = 3) -> list[Verdict]:
    """Несколько контрагентов, на которых стоит посмотреть в первую очередь.

    Порядок здесь обратный `compare`: смотрят первыми тех, к кому больше
    вопросов. Компании без единого вопроса в список не попадают — смотреть
    на них в первую очередь незачем.
    """
    спорные = [в for в in reversed(compare(reports)) if в.level != ЧИСТО]
    return спорные[:limit]


def _перечислить(имена: list[str]) -> str:
    if len(имена) == 1:
        return имена[0]
    return ", ".join(имена[:-1]) + " и " + имена[-1]


# Числительные словами до десяти: «Из 3 чище других» читается как обрывок
# таблицы, а не как фраза. Больше десяти в пуле не показываем.
ЧИСЛИТЕЛЬНЫЕ = {
    2: "двух", 3: "трёх", 4: "четырёх", 5: "пяти",
    6: "шести", 7: "семи", 8: "восьми", 9: "девяти", 10: "десяти",
}


def summary(verdicts: list[Verdict]) -> Summary:
    """Вывод словами: кто выглядит чище и с кем осторожнее.

    Собирается кодом, а не моделью. Экран сравнения должен открываться
    заполненным и переживать недоступность провайдера — ровно как первое
    сообщение в разборе.
    """
    if not verdicts:
        return Summary("Пул пуст", "Добавьте контрагентов по ИНН, чтобы сравнить их.")
    if len(verdicts) == 1:
        return Summary(
            f"В пуле только {verdicts[0].name}",
            "Сравнивать не с чем — добавьте ещё одного контрагента.",
        )

    лучший, худший = verdicts[0], verdicts[-1]
    сколько = ЧИСЛИТЕЛЬНЫЕ.get(len(verdicts), str(len(verdicts)))
    подробности = []

    if лучший.level == ЧИСТО:
        заголовок = f"Из {сколько} чище других выглядит {лучший.name}"
        первая = (
            f"Противоречий между разделами нет, пройдено {лучший.checks_passed} "
            f"проверок из {лучший.checks_total}."
            if лучший.checks_total
            else "Противоречий между разделами нет."
        )
        # Нехватка данных проговаривается именно у верхнего: наверху списка это
        # единственное, что отличает «проверили и чисто» от «нечем было проверить».
        if лучший.gaps:
            первая += (
                f" Но по {'разделу' if len(лучший.gaps) == 1 else 'разделам'} "
                f"«{'», «'.join(лучший.gaps)}» данных нет — проверить было нечем."
            )
        подробности.append(первая)
    else:
        заголовок = f"Чистых среди {сколько} нет"
        подробности.append("Вопросы есть у каждого контрагента в пуле.")

    # Про худшего говорим отдельно и с его собственной причиной. Назвать двоих
    # и привести одну причину значит приписать её обоим.
    if худший.level != ЧИСТО and худший is not лучший:
        причина = худший.reasons[0].lower() if худший.reasons else "см. отчёт"
        глагол = "Осторожнее всего" if худший.level == ВНИМАНИЕ else "Больше всего вопросов"
        подробности.append(f"{глагол} с {худший.name} — {причина}.")

    прочие = [в.name for в in verdicts[1:-1] if в.level != ЧИСТО]
    if прочие:
        подробности.append(f"Вопросы есть и у {_перечислить(прочие)}.")
    elif лучший.level == ЧИСТО and худший.level == ЧИСТО:
        подробности.append("У остальных противоречий между разделами тоже не нашлось.")
    return Summary(заголовок, " ".join(подробности))
